"""`colorRefs[1][]` (Ref read after index) → `colorRefs[0]` after index rewrite; drop trailing `[]`."""
function replace_indexed_julia_ref_cell_reads(data::AbstractString)::String
    s = String(data)
    changed = true
    while changed
        s2 = replace(s, r"([A-Za-z_][\w.]*\[\d+\])\[\]" => s"\1")
        changed = s2 != s
        s = s2
    end
    return s
end

