# Split by commas at top level, ignoring commas inside `{...}`.
function split_top_level_commas(s::AbstractString)::Vector{String}
    out = String[]
    part = IOBuffer()
    depth = 0
    for c in String(s)
        if c == '{'
            depth += 1
            write(part, c)
        elseif c == '}'
            depth -= 1
            write(part, c)
        elseif c == ',' && depth == 0
            push!(out, strip(String(take!(part))))
        else
            write(part, c)
        end
    end
    push!(out, strip(String(take!(part))))
    return out
end

# Split by commas at depth 0; respects `()`, `[]`, `{}`, and `"..."`.
function split_top_level_commas_general(s::AbstractString)::Vector{String}
    s = String(s)
    out = String[]
    part = IOBuffer()
    paren = 0
    bracket = 0
    brace = 0
    i = firstindex(s)
    n = lastindex(s)
    while i <= n
        c = s[i]
        if c == '"'
            endq = _skip_double_quoted_string(s, i, n)
            write(part, SubString(s, i:endq))
            i = nextind(s, endq)
            continue
        end
        if c == '('
            paren += 1
            write(part, c)
        elseif c == ')'
            paren -= 1
            write(part, c)
        elseif c == '['
            bracket += 1
            write(part, c)
        elseif c == ']'
            bracket -= 1
            write(part, c)
        elseif c == '{'
            brace += 1
            write(part, c)
        elseif c == '}'
            # Stray `}` (e.g. malformed `parts[1:]}`) must not make `brace` negative or commas won't split.
            brace = max(0, brace - 1)
            write(part, c)
        elseif c == ',' && paren == 0 && bracket == 0 && brace == 0
            push!(out, strip(String(take!(part))))
        else
            write(part, c)
        end
        i = nextind(s, i)
    end
    push!(out, strip(String(take!(part))))
    return out
end

function _strip_one_outer_paren_pair(r::AbstractString)::Union{Nothing,String}
    t = strip(String(r))
    fi = firstindex(t)
    li = lastindex(t)
    t[fi] != '(' && return nothing
    t[li] != ')' && return nothing
    inner = t[nextind(t, fi):prevind(t, li)]
    return String(strip(inner))
end

function scalar_type_to_ts(t::AbstractString, scalar_map::Dict{String,String})::String
    t = String(strip(t))
    t == "Ptr{Nothing}" && return "null"
    # `Ptr{Mod.Type}` — do not use `split(..., '.')[end]` (leaves a stray `}` on the leaf).
    if startswith(t, "Ptr{") && endswith(t, "}")
        return "any"
    end
    if startswith(t, "Vector{") && endswith(t, "}")
        inner = t[nextind(t, firstindex(t), 7):prevind(t, lastindex(t))]
        return vector_inner_to_ts(inner, scalar_map)
    end
    if haskey(scalar_map, t)
        return scalar_map[t]
    end
    if occursin('.', t)
        leaf = String(split(t, '.')[end])
        return string(get(scalar_map, leaf, leaf))
    end
    return string(get(scalar_map, t, t))
end

# `::Union{A, B, Ptr{Nothing}}` → `: A | B | null` (brace-balanced).
function replace_union_annotations(data::AbstractString, scalar_map::Dict{String,String})::String
    s = String(data)
    needle = "::Union{"
    io = IOBuffer()
    idx = firstindex(s)
    n = lastindex(s)
    while idx <= n
        rg = findnext(needle, s, idx)
        if rg === nothing
            write(io, SubString(s, idx))
            break
        end
        lo = first(rg)
        brace_open = last(rg)
        lo > idx && write(io, SubString(s, idx, prevind(s, lo)))
        depth = 1
        p = nextind(s, brace_open)
        while p <= n && depth > 0
            c = s[p]
            if c == '{'
                depth += 1
            elseif c == '}'
                depth -= 1
            end
            p = nextind(s, p)
        end
        union_inner = s[nextind(s, brace_open):prevind(s, prevind(s, p))]
        members = split_top_level_commas(union_inner)
        ts_members = map(m -> julia_type_expr_to_ts(m, scalar_map), members)
        write(io, ": ", join(ts_members, " | "))
        idx = p
    end
    return String(take!(io))
end

function vector_inner_to_ts(inner::AbstractString, scalar_map::Dict{String,String})::String
    inner = String(strip(inner))
    if haskey(scalar_map, inner)
        return scalar_map[inner] * "[]"
    end
    if occursin('.', inner)
        leaf = String(split(inner, '.')[end])
        return string(get(scalar_map, leaf, leaf)) * "[]"
    end
    return string(get(scalar_map, inner, inner)) * "[]"
end

function replace_empty_vector_literals(data::AbstractString)::String
    s = String(data)
    s = replace(s, "Vector2f()" => "{x: 0, y: 0}")
    s = replace(s, "Vector3f()" => "{x: 0, y: 0, z: 0}")
    s = replace(s, "Vector4()" => "{x: 0, y: 0, z: 0, t: 0}")
    s = replace(s, "Vector2()" => "{x: 0, y: 0}")
    s = replace(s, "Vector3()" => "{x: 0, y: 0, z: 0}")
    s = replace(s, "Vector4()" => "{x: 0, y: 0, z: 0, t: 0}")
    # Value-position typed empty array default (`foo: Bar[] = Bar[]`) -> `foo: Bar[] = []`.
    # Keep type annotations intact; only rewrite RHS when the value ends there (param/list terminator),
    # so ref reads like `result[].w` are untouched.
    s = replace(s, r"=\s*[A-Za-z_][A-Za-z0-9_\.]*\[\](?=\s*(?:[,)\n]|$))" => "= []")
    return s
end

function julia_type_expr_to_ts(t::AbstractString, scalar_map::Dict{String,String})::String
    t = String(strip(t))
    t == "Ptr{Nothing}" && return "null"
    if startswith(t, "Ptr{") && endswith(t, "}")
        inner = String(strip(t[nextind(t, firstindex(t), 4):prevind(t, lastindex(t))]))
        inner == "Nothing" && return "null"
        return "any"
    end
    t == "Nothing" && return "null"
    startswith(t, "Vector{") && endswith(t, "}") && return vector_inner_to_ts(t[nextind(t, firstindex(t), 7):prevind(t, lastindex(t))], scalar_map)
    if startswith(t, "Union{") && endswith(t, "}")
        inner = t[nextind(t, firstindex(t), 6):prevind(t, lastindex(t))]
        members = split_top_level_commas(inner)
        return join(map(m -> julia_type_expr_to_ts(m, scalar_map), members), " | ")
    end
    if startswith(t, "NTuple{") && endswith(t, "}")
        inner = t[nextind(t, firstindex(t), 7):prevind(t, lastindex(t))]
        parts = split_top_level_commas(inner)
        if length(parts) == 2
            n = tryparse(Int, strip(parts[1]))
            item_ts = julia_type_expr_to_ts(parts[2], scalar_map)
            n !== nothing && n >= 1 && n <= 16 && return "[" * join(fill(item_ts, n), ", ") * "]"
            return item_ts * "[]"
        end
    end
    if haskey(scalar_map, t)
        return scalar_map[t]
    end
    if occursin('.', t)
        leaf = String(split(t, '.')[end])
        return string(get(scalar_map, leaf, leaf))
    end
    return string(get(scalar_map, t, t))
end

function replace_struct_field_annotations(data::AbstractString, scalar_map::Dict{String,String})::String
    lines = split(String(data), '\n'; keepempty = true)
    # Allow trailing inline comments so `field::Bool  // ...` still rewrites to `field: boolean  // ...`.
    pat = r"^(\s*[A-Za-z_]\w*)::\s*([^/\n=]+?)(\s*//.*)?\s*$"
    out = map(lines) do line
        m = match(pat, line)
        m === nothing && return line
        trailing = m[3] === nothing ? "" : String(m[3])
        string(m[1], ": ", julia_type_expr_to_ts(String(m[2]), scalar_map), trailing)
    end
    return join(out, '\n')
end

function replace_header_param_annotations(data::AbstractString, scalar_map::Dict{String,String})::String
    lines = split(String(data), '\n'; keepempty = true)
    header_pat = r"^(\s*(?:function\s+[^\s(]+|constructor)\s*\()([^)]*)(\).*)$"
    out = map(lines) do line
        hm = match(header_pat, line)
        hm === nothing && return line
        # Julia `f(a::T; b = 1)` — semicolon separates kwargs; TS uses commas only.
        params_str = String(strip(String(hm[2])))
        params_str = replace(params_str, r"\s*;\s*" => ", ")
        raw_parts = split_top_level_commas_general(params_str)
        params = [String(strip(p)) for p in raw_parts if !isempty(strip(String(p)))]
        rewritten = map(params) do p
            ps = String(strip(String(p)))
            pm = match(r"^(\s*[A-Za-z_]\w*)::\s*([^=]+?)(\s*=\s*.*)?\s*$", ps)
            if pm !== nothing
                name = String(pm[1])
                typ = julia_type_expr_to_ts(String(pm[2]), scalar_map)
                defaultv = pm[3] === nothing ? "" : String(pm[3])
                defaultv = replace(defaultv, r"=\s*nothing\b" => "= null")
                return string(name, ": ", typ, defaultv)
            end
            # Untyped `name = nothing` / `name = null` — TS otherwise infers param as literal `null`
            # and `param !== null` narrows to `never` in the true branch (TS2339 on `.position`, etc.).
            pm2 = match(r"^(\s*[A-Za-z_]\w*)\s*=\s*(.+)$", ps)
            if pm2 !== nothing
                defaultv = String(strip(String(pm2[2])))
                if defaultv == "nothing" || defaultv == "null"
                    return string(String(pm2[1]), ": any = null")
                end
            end
            return p
        end
        string(hm[1], join(rewritten, ", "), hm[3])
    end
    return join(out, '\n')
end

# `::Vector{Inner}` → `: ts[]` using scalar_map for bare names and the last segment for `Mod.Type`.
# Nested `Vector{Vector{Int}}` is not supported (single `[^}]+` capture).
function replace_vector_annotations(data::AbstractString, scalar_map::Dict{String,String})
    s = String(data)
    pat = r"::Vector\{([^}]+)\}"
    io = IOBuffer()
    idx = firstindex(s)
    n = lastindex(s)
    while idx <= n
        rg = findnext(pat, s, idx)
        if rg === nothing
            write(io, SubString(s, idx))
            break
        end
        f = first(rg)
        f > idx && write(io, SubString(s, idx, prevind(s, f)))
        m = match(pat, s, f)
        m === nothing && break
        inner = m[1]::AbstractString
        write(io, ": ", vector_inner_to_ts(inner, scalar_map))
        idx = nextind(s, last(rg))
    end
    return String(take!(io))
end

