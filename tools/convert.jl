"""
    ts_output_path(jl_path; repo_root, generated_dir)

Build the `.ts` path as: `joinpath(repo_root, generated_dir, <same relative dirs as jl_path>, <stem>.ts)`.

Example: `repo/src/engine/Foo.jl` → `repo/_generated/src/engine/Foo.ts`

You cannot “edit” a `joinpath` result in place — strings are immutable. Split with `splitdir` / `relpath`, then `joinpath` again.
"""
function ts_output_path(
    jl_path::AbstractString;
    repo_root::AbstractString = REPO_ROOT,
    generated_dir::AbstractString = "_generated",
)::String
    abs_jl = abspath(jl_path)
    abs_root = abspath(repo_root)
    rel = try
        relpath(abs_jl, abs_root)
    catch
        splitdir(abs_jl)[2]  # basename-only fallback
    end
    rel_dir, rel_file = splitdir(rel)
    stem = splitext(rel_file)[1]
    isempty(rel_dir) && return joinpath(abs_root, "ts", generated_dir, stem * ".ts")
    joinpath(abs_root, "ts", generated_dir, rel_dir, stem * ".ts")
end

function emit_stub(path_ts::AbstractString, path_jl::AbstractString)
    mkpath(dirname(path_ts))
    rel = try
        relpath(path_jl, REPO_ROOT)
    catch
        path_jl
    end
    open(path_ts, "w") do io
        println(io, "// Generated by tools/convert.jl from ", rel)
        println(io, "// Stub: transpiler not implemented for this file.")
        println(io, "export {}")
    end
    path_ts
end

function transpile_file(path_jl::AbstractString; repo_root::AbstractString = REPO_ROOT)
    path_ts = ts_output_path(path_jl; repo_root = repo_root)
    emit_stub(path_ts, path_jl)
    parse_file(path_jl, path_ts; repo_root = repo_root)
end

function parse_file(
    path_jl::AbstractString,
    path_ts::AbstractString;
    repo_root::AbstractString = REPO_ROOT,
)
    _ = repo_root
    mkpath(dirname(path_ts))
    data = read(path_jl, String)
    # Drop UTF-8 BOMs copied from source files so generated TS starts cleanly.
    data = replace(data, "\ufeff" => "")
    data = replace_module(data)
    data = replace_end(data)
    data = replace_exports(data)
    data = replace_comments(data)
    data = replace_docstrings(data)
    data = replace_imports_usings_includes(data)
    data = replace_mutable_structs(data)
    data = replace_structs(data)
    data = replace_types(data)
    data = replace_constructor(data)
    data = replace_function_declaration_dots(data)
    data = replace_component_qualified_calls(data)
    data = replace_function_definitions(data)
    data = replace_if_statements(data)
    data = replace_while_statements(data)
    data = replace_else_elseif_blocks(data)
    data = replace_for_in_loops(data)
    data = replace_first_assignments_with_let(data)
    data = replace_julia_ts_literals(data)
    data = replace_while_statements(data)
    data = normalize_julia_ref_for_ts(data)
    # After `glue_SDL_Event[]` → `glue_SDL_Event` (ref-strip), empty SDL event queue must be `[]`.
    data = replace(
        data,
        r"(?m)^(\s*(?:this|self)\.pending_sdl_events\s*=\s*)\(globalThis as any\)\.JulGameSdl\.glue_SDL_Event\s*$" => s"\1[]",
    )
    data = replace_let_named_tuple_rhs_to_object(data)
    data = insert_semicolon_before_line_starting_with_open_paren(data)
    data = replace_invokelatest_calls(data)
    data = replace_julia_semicolon_kw_calls_to_commas(data)
    data = replace_keyword_style_calls_to_object_args(data)
    data = replace_animation_symbol(data)
    data = custom_function_removal(data, path_jl)
    data = replace_push_calls(data)
    data = remove_!_from_function_names(data)
    # `JulGame.foo` → `(globalThis...).JulGame.foo` and `!(...)` rewrites can create new line-leading `(`.
    data = insert_semicolon_before_line_starting_with_open_paren(data)
    data = replace_popfirst_calls(data)
    data = replace_deleteat_calls(data)
    data = replace_findfirst_equality_calls(data)
    data = replace_setfield_calls(data)
    data = replace_empty_vector_literals(data)
    data = rewrite_rhs_vector_arithmetic(data)
    data = prefix_new_for_listed_class_constructors(data)
    data = rename_julia_this_receiver_to_self(data)
    data = replace_julia_ts_fixup_pass(data, path_jl)
    data = replace_ts_if_blocks_when_block_contains_substring(data)
    data = replace_entire_line_if_matches(data, path_jl)
    data = merge_main_scene_delegating_overloads(data)
    data = normalize_julgame_global_access(data)
    is_script = is_game_script_source(path_jl)
    if is_input_source(path_jl)
        data = postprocess_input_ts(data, path_jl, path_ts)
    elseif is_script
        data = postprocess_game_script_ts(data, path_jl, path_ts)
    else
        data = "export {}\n" * data
        is_collider_source(path_jl) && (data = postprocess_collider_ts(data))
        is_sound_source(path_jl) && (data = postprocess_sound_ts(data))
        is_animator_source(path_jl) && (data = postprocess_animator_ts(data))
        is_sprite_source(path_jl) && (data = postprocess_sprite_ts(data))
    end
    if !is_script
        data = prepend_generated_ts_imports(data, path_ts)
    end
    # Input.ts exports are finalized in `postprocess_input_ts` (`tools/convert/input.jl`).
    if !is_input_source(path_jl) && !is_script
        data = append_generated_module_exports(data)
    end
    is_camera_source(path_jl) && (data = finalize_camera_exports(data))
    open(path_ts, "w") do io
        print(io, data)
    end
    path_ts
end

function _line_is_julia_style_internal_ctor_decl(line::AbstractString)::Bool
    m = match(r"^\s*function\s+(\w+)\s*\(", line)
    m === nothing && return false
    return String(m[1]) in TS_CLASS_NAMES_NEEDING_NEW
end

function prefix_new_for_listed_class_constructors(data::AbstractString)::String
    lines = split(String(data), '\n'; keepempty = true)
    out = map(lines) do line
        _line_is_julia_style_internal_ctor_decl(line) && return line
        sline = String(line)
        for t in TS_CLASS_NAMES_NEEDING_NEW
            pat = Regex("(?<!\\bnew\\s)(?<!\\.)\\b" * t * "\\s*\\(")
            sline = replace(sline, pat => "new $(t)(")
        end
        return sline
    end
    return join(out, '\n')
end

function prepend_generated_ts_imports(data::AbstractString, path_ts::AbstractString)::String
    need_clamp = occursin(r"\bclamp\s*\(", data)
    need_unsafe_string = occursin(r"\bunsafe_string\s*\(", data)
    need_unsafe_wrap = occursin(r"\bunsafe_wrap\s*\(", data)
    need_joinpath = occursin(r"\bjoinpath\s*\(", data)
    need_haskey = occursin(r"\bhaskey\s*\(", data)
    need_pointer = occursin(r"\bpointer\s*\(", data)
    need_mix_volume = occursin(r"\bmixVolume\s*\(", data)
    need_time_ns = occursin(r"\btime_ns\s*\(", data)
    need_vec = occursin(r"\bvec(Add|Sub|Mul|Div|Neg)\(", data)
    ts_dir = dirname(abspath(path_ts))
    lines = String[]
    if need_clamp || need_unsafe_string || need_unsafe_wrap || need_joinpath || need_haskey || need_pointer || need_mix_volume || need_time_ns
        h = abspath(joinpath(REPO_ROOT, "ts", "src", "engine", "core", "juliaHelpers.ts"))
        if isfile(h)
            rel = replace(String(relpath(h, ts_dir)), '\\' => '/')
            rel = replace(rel, r"\.ts$" => "")
            syms = String[]
            need_clamp && push!(syms, "clamp")
            need_haskey && push!(syms, "haskey")
            need_pointer && push!(syms, "pointer")
            need_mix_volume && push!(syms, "mixVolume")
            need_joinpath && push!(syms, "joinpath")
            need_time_ns && push!(syms, "time_ns")
            need_unsafe_string && push!(syms, "unsafe_string")
            need_unsafe_wrap && push!(syms, "unsafe_wrap")
            sort!(syms)
            push!(lines, string("import { ", join(syms, ", "), " } from \"", rel, "\";"))
        end
    end
    if need_vec
        v = abspath(joinpath(REPO_ROOT, "ts", "src", "engine", "core", "vectorOps.ts"))
        if isfile(v)
            relv = replace(String(relpath(v, ts_dir)), '\\' => '/')
            relv = replace(relv, r"\.ts$" => "")
            push!(lines, string("import { vecAdd, vecSub, vecMul, vecDiv, vecNeg } from \"", relv, "\";"))
        end
    end
    # Cross-module component / transform imports (paths in dict are relative to `_generated/src/engine`).
    engine_ts_root = abspath(joinpath(REPO_ROOT, "ts", "_generated", "src", "engine"))
    by_path = Dict{String, Vector{String}}()
    for (sym, (engine_rel, _)) in _CROSS_MODULE_SYMBOL_SOURCES
        occursin(Regex("\\b" * sym * "\\b"), data) || continue
        # Do not import symbols defined in this file (e.g. `class Camera`, `function Component_initialize`).
        occursin(Regex("class\\s+" * sym * "\\s*\\{"), data) && continue
        occursin(Regex("function\\s+" * sym * "\\s*\\("), data) && continue
        occursin(Regex("import\\s+\\{[^}]*\\b" * sym * "\\b"), data) && continue
        module_rel = replace(String(engine_rel), r"^\./" => "")
        target_ts = joinpath(engine_ts_root, module_rel * ".ts")
        import_from = replace(String(relpath(target_ts, ts_dir)), '\\' => '/')
        import_from = replace(import_from, r"\.ts$" => "")
        startswith(import_from, ".") || (import_from = "./" * import_from)
        syms = get!(by_path, import_from, String[])
        sym in syms || push!(syms, sym)
    end
    for import_from in sort(collect(keys(by_path)))
        syms = sort!(by_path[import_from])
        push!(lines, string("import { ", join(syms, ", "), " } from \"", import_from, "\";"))
    end
    isempty(lines) && return data
    import_block = string(join(lines, "\n"), "\n")
    data_lines = split(String(data), '\n'; keepempty = true)
    if !isempty(data_lines) && strip(data_lines[1]) == "export {}"
        return string(data_lines[1], "\n", import_block, "\n", join(data_lines[2:end], '\n'))
    end
    return string(import_block, "\n", data)
end

# --- Julia-style vector `+ - * /` on plain `{x,y}` / `{x,y,z}` objects (see `src/Math/Vector2.jl`, `Math.jl`) ---

abstract type _VecAst end

struct _Leaf <: _VecAst
    text::String
end

struct _Neg <: _VecAst
    child::_VecAst
end

struct _Bin <: _VecAst
    op::Char
    left::_VecAst
    right::_VecAst
end

struct _Call <: _VecAst
    name::String
    args::Vector{_VecAst}
end

struct _Idx <: _VecAst
    base::_VecAst
    inner::_VecAst
end

mutable struct _Ps
    s::String
    i::Int
    n::Int
end

function _skip_ws!(ps::_Ps)
    while ps.i <= ps.n
        c = ps.s[ps.i]
        (c == ' ' || c == '\t') || break
        ps.i = nextind(ps.s, ps.i)
    end
end

function _peekc(ps::_Ps)::Union{Nothing, Char}
    _skip_ws!(ps)
    ps.i > ps.n && return nothing
    return ps.s[ps.i]
end

const _VECTOR_RHS_GTA_PLACEHOLDER = "__JulGame_GlobalThisJulGame__"

function _vec_ts_cast_suffix(lhs::AbstractString)::String
    ls = String(strip(lhs))
    # Narrow names so we do not cast e.g. `screenPosition` (Vector2) to Vector3f.
    if ls in ("newPosition", "currentPosition", "targetPos")
        return " as Vector3f"
    end
    if ls in (
        "newVelocity",
        "this.velocity",
        "this.acceleration",
        "velocityMultiplier",
        "newAcceleration",
        "gravityAcceleration",
        "dragAcceleration",
        "dragForce",
        "posA",
        "posB",
    )
        return " as Vector2f"
    end
    return ""
end

function _rhs_hints_vector_math(rhs::AbstractString)::Bool
    occursin(r"[+\-*/]", rhs) || return false
    occursin("velocity", rhs) ||
        occursin("acceleration", rhs) ||
        occursin("transform.position", rhs) ||
        occursin("gravityAcceleration", rhs) ||
        occursin("dragAcceleration", rhs) ||
        occursin("dragForce", rhs) ||
        occursin("velocityMultiplier", rhs) ||
        occursin("newVelocity", rhs) ||
        occursin("newPosition", rhs) ||
        occursin("newAcceleration", rhs) ||
        occursin("currentPosition", rhs) ||
        (occursin(".offset", rhs) && occursin("position", rhs))
    # Do not key off `SCALE_UNITS` alone — scalar chains like `scale.x * size.x * SCALE_UNITS` must stay numeric.
end

function _normalize_ts_casts_for_vec_parse(rhs::AbstractString)::String
    replace(String(rhs), r"\(\s*globalThis\s+as\s+any\s*\)" => _VECTOR_RHS_GTA_PLACEHOLDER)
end

function _restore_ts_casts_after_vec_emit(emitted::AbstractString)::String
    replace(String(emitted), _VECTOR_RHS_GTA_PLACEHOLDER => "(globalThis as any)")
end

function _emit_vec_ast(node::_VecAst)::String
    if node isa _Leaf
        return node.text
    elseif node isa _Neg
        return string("vecNeg(", _emit_vec_ast(node.child), ")")
    elseif node isa _Bin
        fn = node.op == '+' ? "vecAdd" :
             node.op == '-' ? "vecSub" :
             node.op == '*' ? "vecMul" : "vecDiv"
        return string(fn, "(", _emit_vec_ast(node.left), ", ", _emit_vec_ast(node.right), ")")
    elseif node isa _Call
        parts = map(_emit_vec_ast, node.args)
        return string(node.name, "(", join(parts, ", "), ")")
    elseif node isa _Idx
        return string(_emit_vec_ast(node.base), "[", _emit_vec_ast(node.inner), "]")
    else
        return ""
    end
end

function _read_atom_token!(ps::_Ps)::Union{Nothing, String}
    _skip_ws!(ps)
    ps.i > ps.n && return nothing
    i0 = ps.i
    c = ps.s[ps.i]
    if isdigit(c) ||
        (c == '.' && ps.i < ps.n && isdigit(ps.s[nextind(ps.s, ps.i)]))
        while ps.i <= ps.n
            cc = ps.s[ps.i]
            if isdigit(cc) || cc == '.' || cc in ('e', 'E', '+', '-')
                ps.i = nextind(ps.s, ps.i)
            else
                break
            end
        end
        return String(SubString(ps.s, i0, prevind(ps.s, ps.i)))
    end
    if isletter(c) || c == '_' || c == '$'
        while ps.i <= ps.n
            cc = ps.s[ps.i]
            if isletter(cc) || isdigit(cc) || cc in ('_', '$', '.')
                ps.i = nextind(ps.s, ps.i)
            else
                break
            end
        end
        return String(SubString(ps.s, i0, prevind(ps.s, ps.i)))
    end
    return nothing
end

function _read_braced_atom!(ps::_Ps)::Union{Nothing, String}
    _skip_ws!(ps)
    ps.i > ps.n && return nothing
    ps.s[ps.i] != '{' && return nothing
    i0 = ps.i
    depth = 0
    while ps.i <= ps.n
        c = ps.s[ps.i]
        if c == '"'
            ps.i = nextind(ps.s, ps.i)
            while ps.i <= ps.n
                cc = ps.s[ps.i]
                if cc == '\\'
                    ps.i = nextind(ps.s, ps.i, 2)
                    continue
                end
                if cc == '"'
                    ps.i = nextind(ps.s, ps.i)
                    break
                end
                ps.i = nextind(ps.s, ps.i)
            end
            continue
        end
        if c == '{'
            depth += 1
        elseif c == '}'
            depth -= 1
            if depth == 0
                i1 = ps.i
                ps.i = nextind(ps.s, ps.i)
                return String(SubString(ps.s, i0, i1))
            end
        end
        ps.i = nextind(ps.s, ps.i)
    end
    return nothing
end

function _parse_postfix!(ps::_Ps)::Union{Nothing, _VecAst}
    c0 = _peekc(ps)
    c0 === nothing && return nothing
    local node::_VecAst
    if c0 == '('
        ps.i = nextind(ps.s, ps.i)
        inner = _parse_addsub!(ps)
        inner === nothing && return nothing
        _skip_ws!(ps)
        (ps.i > ps.n || ps.s[ps.i] != ')') && return nothing
        ps.i = nextind(ps.s, ps.i)
        node = inner
    elseif c0 == '{'
        br = _read_braced_atom!(ps)
        br === nothing && return nothing
        node = _Leaf(br)
    else
        tok = _read_atom_token!(ps)
        tok === nothing && return nothing
        node = _Leaf(tok)
    end
    while true
        c = _peekc(ps)
        c === nothing && break
        if c == '['
            ps.i = nextind(ps.s, ps.i)
            ix = _parse_addsub!(ps)
            ix === nothing && return nothing
            _skip_ws!(ps)
            (ps.i > ps.n || ps.s[ps.i] != ']') && return nothing
            ps.i = nextind(ps.s, ps.i)
            node = _Idx(node, ix)
        elseif c == '('
            node isa _Leaf || return nothing
            name = node.text
            ps.i = nextind(ps.s, ps.i)
            args = _VecAst[]
            c2 = _peekc(ps)
            if c2 == ')'
                ps.i = nextind(ps.s, ps.i)
                node = _Call(name, args)
                continue
            end
            while true
                arg = _parse_addsub!(ps)
                arg === nothing && return nothing
                push!(args, arg)
                c3 = _peekc(ps)
                c3 === nothing && return nothing
                if c3 == ','
                    ps.i = nextind(ps.s, ps.i)
                    continue
                elseif c3 == ')'
                    ps.i = nextind(ps.s, ps.i)
                    break
                else
                    return nothing
                end
            end
            node = _Call(name, args)
        else
            break
        end
    end
    return node
end

function _parse_unary!(ps::_Ps)::Union{Nothing, _VecAst}
    c = _peekc(ps)
    if c == '-'
        ps.i = nextind(ps.s, ps.i)
        ch = _parse_unary!(ps)
        ch === nothing && return nothing
        return _Neg(ch)
    end
    return _parse_postfix!(ps)
end

function _parse_muldiv!(ps::_Ps)::Union{Nothing, _VecAst}
    left = _parse_unary!(ps)
    left === nothing && return nothing
    while true
        c = _peekc(ps)
        c === nothing && break
        if c == '*' || c == '/'
            ps.i = nextind(ps.s, ps.i)
            right = _parse_unary!(ps)
            right === nothing && return nothing
            left = _Bin(c, left, right)
        else
            break
        end
    end
    return left
end

function _parse_addsub!(ps::_Ps)::Union{Nothing, _VecAst}
    left = _parse_muldiv!(ps)
    left === nothing && return nothing
    while true
        c = _peekc(ps)
        c === nothing && break
        if c == '+' || c == '-'
            ps.i = nextind(ps.s, ps.i)
            right = _parse_muldiv!(ps)
            right === nothing && return nothing
            left = _Bin(c, left, right)
        else
            break
        end
    end
    return left
end

function _try_rewrite_rhs_vector_expr(rhs::AbstractString)::Union{Nothing, String}
    r = String(strip(rhs))
    isempty(r) && return nothing
    occursin('"', r) && return nothing
    occursin('\'', r) && return nothing
    r = _normalize_ts_casts_for_vec_parse(r)
    ps = _Ps(r, firstindex(r), lastindex(r))
    tree = _parse_addsub!(ps)
    tree === nothing && return nothing
    _skip_ws!(ps)
    while ps.i <= ps.n && ps.s[ps.i] == ';'
        ps.i = nextind(ps.s, ps.i)
    end
    _skip_ws!(ps)
    ps.i <= ps.n && return nothing
    return _restore_ts_casts_after_vec_emit(_emit_vec_ast(tree))
end

function _matching_paren_close(s::String, open_at::Int)::Union{Nothing, Int}
    depth = 0
    i = open_at
    n = lastindex(s)
    while i <= n
        c = s[i]
        if c == '"'
            j = i
            i = nextind(s, i)
            while i <= n
                cc = s[i]
                if cc == '\\'
                    i = nextind(s, i, 2)
                    continue
                end
                if cc == '"'
                    break
                end
                i = nextind(s, i)
            end
        elseif c == '('
            depth += 1
        elseif c == ')'
            depth -= 1
            depth == 0 && return i
        end
        i = nextind(s, i)
    end
    return nothing
end

function _try_rewrite_set_velocity_line(line::String)::Union{Nothing, String}
    f = findfirst("set_velocity", line)
    f === nothing && return nothing
    i0 = first(f)
    i = last(f)
    while i <= lastindex(line) && line[i] != '('
        i = nextind(line, i)
    end
    i > lastindex(line) && return nothing
    close_i = _matching_paren_close(line, i)
    close_i === nothing && return nothing
    inner = String(SubString(line, nextind(line, i), prevind(line, close_i)))
    parts = split_top_level_commas_general(inner)
    length(parts) < 2 && return nothing
    arg2 = String(strip(parts[2]))
    !_rhs_hints_vector_math(arg2) && return nothing
        rew = _try_rewrite_rhs_vector_expr(arg2)
        rew === nothing && return nothing
        new_inner = string(strip(parts[1]), ", ", rew, " as Vector2f")
    prefix = String(SubString(line, 1, prevind(line, i)))
    suffix = String(SubString(line, nextind(line, close_i)))
    return string(prefix, "(", new_inner, ")", suffix)
end

function _rewrite_vector_arithmetic_line(line::AbstractString)::String
    s = String(rstrip(line, '\r'))
    if occursin("set_velocity", s)
        rw = _try_rewrite_set_velocity_line(s)
        rw !== nothing && return rw
    end
    m = match(r"^(\s*let\s+)([A-Za-z_$]\w*)\s*=\s*(.+)$", s)
    if m !== nothing
        rhs = String(strip(m[3]))
        (startswith(rhs, "{") || startswith(rhs, "[") || startswith(rhs, "`")) && return line
        occursin('"', rhs) && return line
        !_rhs_hints_vector_math(rhs) && return line
        rhs0 = rstrip(rhs, ';')
        rew = _try_rewrite_rhs_vector_expr(rhs0)
        if rew !== nothing
            cast = _vec_ts_cast_suffix(String(m[2]))
            return string(m[1], m[2], " = ", rew, cast)
        end
    end
    m2 = match(r"^(\s*return\s+)(.+)$", s)
    if m2 !== nothing
        rhs = String(strip(m2[2]))
        occursin('"', rhs) && return line
        !_rhs_hints_vector_math(rhs) && return line
        rhs0 = rstrip(rhs, ';')
        rew = _try_rewrite_rhs_vector_expr(rhs0)
        if rew !== nothing
            return string(m2[1], rew, " as Vector2f")
        end
    end
    m3 = match(r"^(\s*)(.+)\s*=\s*(.+)$", s)
    if m3 !== nothing
        lhs = String(strip(m3[2]))
        rhs = String(strip(m3[3]))
        (startswith(rhs, "{") && !occursin('+', rhs) && !occursin('-', rhs)) && return line
        startswith(rhs, "[") && return line
        startswith(rhs, "`") && return line
        occursin('"', rhs) && return line
        (occursin("transform.position", lhs) || endswith(lhs, ".position") ||
         endswith(lhs, ".velocity") || occursin(".velocity", lhs)) || return line
        !_rhs_hints_vector_math(rhs) && return line
        rhs0 = rstrip(rhs, ';')
        rew = _try_rewrite_rhs_vector_expr(rhs0)
        if rew !== nothing
            return string(m3[1], lhs, " = ", rew)
        end
    end
    return line
end

function rewrite_rhs_vector_arithmetic(data::AbstractString)::String
    s = String(data)
    parts = split(s, '\n')
    return join(map(_rewrite_vector_arithmetic_line, parts), '\n')
end

