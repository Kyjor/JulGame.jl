# After `function Foo(...)` → `constructor(...)`, kwargs may still use Julia `;` — TS needs commas.
function replace_constructor_param_list_semicolons_to_commas(data::AbstractString)::String
    lines = split(String(data), '\n'; keepempty = true)
    join(
        map(lines) do line
            line = String(line)
            crg = findfirst("constructor(", line)
            crg === nothing && return line
            oi = last(crg)
            inner_start = nextind(line, oi)
            n = lastindex(line)
            close_idx = _find_outer_push_close(line, inner_start, n)
            close_idx === nothing && return line
            inner = String(line[inner_start:prevind(line, close_idx)])
            inner2 = replace(inner, r"\s*;\s*" => ", ")
            inner2 == inner && return line
            string(line[1:prevind(line, inner_start)], inner2, line[nextind(line, close_idx):n])
        end,
        '\n',
    )
end

# Some constructor headers can lose the final `)` during earlier regex rewrites.
# If we see `constructor(... {` with no parsable matching `)`, patch it to `constructor(...) {`.
function repair_constructor_headers_missing_close_paren(data::AbstractString)::String
    lines = split(String(data), '\n'; keepempty = true)
    out = map(lines) do raw
        line = String(raw)
        startswith(strip(line), "constructor(") || return line
        oi_rg = findfirst("constructor(", line)
        oi_rg === nothing && return line
        oi = last(oi_rg)
        inner_start = nextind(line, oi)
        n = lastindex(line)
        close_idx = _find_outer_push_close(line, inner_start, n)
        close_idx !== nothing && return line
        bi = findfirst('{', line)
        bi === nothing && return line
        head = String(rstrip(SubString(line, 1, prevind(line, bi))))
        endswith(head, ")") && return line
        tail = String(SubString(line, bi, n))
        return string(head, ") ", tail)
    end
    return join(out, '\n')
end

# Julia instance param `this::T` becomes TS `this: T`, but TS treats `this` as a fake parameter (not a real
# argument, and `this` in body is often `void`). Rename to `self` in decl + matching function body.
function rename_julia_this_receiver_to_self(data::AbstractString)::String
    lines = split(String(data), '\n'; keepempty = true)
    out = String[]
    decl_pat = r"^(\s*)function\s+\w+\s*\(\s*this\s*:"
    i = 1
    n = length(lines)
    function _brace_delta(line::AbstractString)::Int
        d = 0
        for c in line
            if c == '{'
                d += 1
            elseif c == '}'
                d -= 1
            end
        end
        return d
    end
    while i <= n
        line = String(lines[i])
        occursin(decl_pat, line) || (push!(out, line); i += 1; continue)
        decl_line = replace(line, r"\(\s*this\s*:" => "(self:", count = 1)
        push!(out, decl_line)
        i += 1
        balance = _brace_delta(decl_line)
        while i <= n && balance > 0
            body = String(lines[i])
            body = replace(body, r"\bthis\." => "self.")
            body = replace(body, r"\bthis\b" => "self")
            push!(out, body)
            balance += _brace_delta(body)
            i += 1
        end
    end
    return join(out, '\n')
end

function replace_constructor(data::AbstractString)
    # Julia inner ctor is `function ClassName(args)` (no `{`). Only the ctor whose name
    # matches a `class Name {` in this file becomes `constructor(args)`.
    seen = Set{String}()
    for m in eachmatch(r"class\s+(\w+)\s*\{", data)
        name = m.captures[1]::AbstractString
        name in seen && continue
        push!(seen, name)
        # `name` comes from `(\w+)` on the class line — no regex metacharacters to escape.
        pat = Regex("function\\s+" * string(name) * "\\s*\\(")
        data = replace(data, pat => "constructor(")
    end
    # TS needs `{` before the body; do this line-wise so nested `)` in defaults do not break.
    lines = split(String(data), '\n'; keepempty = true)
    lines = map(lines) do line
        startswith(strip(line), "constructor(") || return line
        occursin('{', line) && return line
        return line * " {"
    end
    data = join(lines, '\n')

    data = replace(data, "this = new()" => "")
    # Only the ctor idiom `return this` on its own line — not `return this.foo`.
    data = replace(data, r"(?m)^\s*return this\s*$" => "")
    data = replace_constructor_param_list_semicolons_to_commas(data)
    data = repair_constructor_headers_missing_close_paren(data)
    return data
end

# `function A.B.c(` → `function A_B_c(` — TS cannot use `.` in a `function` name.
# Uses `findnext` + `match` (no `replace(str, regex, f)` — that overload is newer Julia).
function replace_function_declaration_dots(data::AbstractString)
    s = String(data)
    pat = r"(?m)^(\s*function\s+)([^\s(]+)(\()"
    io = IOBuffer()
    idx = firstindex(s)
    n = lastindex(s)
    while idx <= n
        rg = findnext(pat, s, idx)
        if rg === nothing
            write(io, SubString(s, idx))
            break
        end
        f = first(rg)
        f > idx && write(io, SubString(s, idx, prevind(s, f)))
        m = match(pat, s, f)
        m === nothing && break
        write(io, string(m[1], replace(m[2], "." => "_"), m[3]))
        idx = nextind(s, last(rg))
    end
    return String(take!(io))
end

