#!/usr/bin/env julia
# Julia → TypeScript stub emitter (extend later).
#
#   julia convert.jl
#
# Output path rule: <REPO_ROOT>/_generated/<mirror-of-relative-path>.ts

const REPO_ROOT = normpath(joinpath(@__DIR__, ".."))

default_out_dir() = joinpath(REPO_ROOT, "ts", "_generated")

"""
    ts_output_path(jl_path; repo_root, generated_dir)

Build the `.ts` path as: `joinpath(repo_root, generated_dir, <same relative dirs as jl_path>, <stem>.ts)`.

Example: `repo/src/engine/Foo.jl` → `repo/_generated/src/engine/Foo.ts`

You cannot “edit” a `joinpath` result in place — strings are immutable. Split with `splitdir` / `relpath`, then `joinpath` again.
"""
function ts_output_path(
    jl_path::AbstractString;
    repo_root::AbstractString = REPO_ROOT,
    generated_dir::AbstractString = "_generated",
)::String
    abs_jl = abspath(jl_path)
    abs_root = abspath(repo_root)
    rel = try
        relpath(abs_jl, abs_root)
    catch
        splitdir(abs_jl)[2]  # basename-only fallback
    end
    rel_dir, rel_file = splitdir(rel)
    stem = splitext(rel_file)[1]
    isempty(rel_dir) && return joinpath(abs_root, "ts", generated_dir, stem * ".ts")
    joinpath(abs_root, "ts", generated_dir, rel_dir, stem * ".ts")
end

function emit_stub(path_ts::AbstractString, path_jl::AbstractString)
    mkpath(dirname(path_ts))
    rel = try
        relpath(path_jl, REPO_ROOT)
    catch
        path_jl
    end
    open(path_ts, "w") do io
        println(io, "// Generated by tools/convert.jl from ", rel)
        println(io, "// Stub: transpiler not implemented for this file.")
        println(io, "export {}")
    end
    path_ts
end

function transpile_file(path_jl::AbstractString)
    path_ts = ts_output_path(path_jl)
    emit_stub(path_ts, path_jl)
    parse_file(path_jl, path_ts)
end

function parse_file(path_jl::AbstractString, path_ts::AbstractString)
    mkpath(dirname(path_ts))
    data = read(path_jl, String)
    data = replace_module(data)
    data = replace_end(data)
    data = replace_exports(data)
    data = replace_comments(data)
    data = replace_docstrings(data)
    data = replace_imports_usings_includes(data)
    data = replace_mutable_structs(data)
    data = replace_structs(data)
    data = replace_types(data)
    data = replace_constructor(data)
    data = replace_function_declaration_dots(data)
    data = replace_component_qualified_calls(data)
    data = replace_function_definitions(data)
    data = replace_if_statements(data)
    data = replace_for_in_loops(data)
    data = replace_first_assignments_with_let(data)
    data = replace_julia_ts_literals(data)
    data = normalize_julgame_global_access(data)
    data = replace_animation_symbol(data)
    data = custom_function_removal(data)
    data = replace_push_calls(data)
    data = remove_!_from_function_names(data)
    data = replace_setfield_calls(data)
    data = "export {}\n" * data
    open(path_ts, "w") do io
        print(io, data)
    end
    path_ts
end

function replace_module(data::AbstractString)
    # replace the line with module with empty string
    data = replace(data, r"module .*" => "")
    # `findlast("end", s)` returns a `UnitRange` of indices, not one integer
    r = findlast("end", data)
    r === nothing && return data
    head = data[1:prevind(data, first(r))]
    return head * ""
end

function replace_end(data::AbstractString)
    # Julia block closer only: plain `r"end"` would mangle identifiers like `append_*`.
    data = replace(data, r"\bend\b" => "}")
    return data
end

function replace_exports(data::AbstractString)
    # replace the line with export with empty string
    data = replace(data, r"export .*" => "")
    return data
end

function replace_comments(data::AbstractString)
    # replace the line with # with empty string
    data = replace(data, r"#" => "//")
    return data
end

# Julia `""" ... """` docstrings → TS block comments. Run after `#` → `//` inside the doc body.
# Break `*/` in the body so the comment does not end early.
function replace_docstrings(data::AbstractString)::String
    s = String(data)
    delim = "\"\"\""
    io = IOBuffer()
    idx = firstindex(s)
    n = lastindex(s)
    while idx <= n
        rg_open = findnext(delim, s, idx)
        if rg_open === nothing
            write(io, SubString(s, idx))
            break
        end
        lo = first(rg_open)
        lo > idx && write(io, SubString(s, idx, prevind(s, lo)))
        inner_start = nextind(s, last(rg_open))
        rg_close = findnext(delim, s, inner_start)
        if rg_close === nothing
            write(io, SubString(s, idx))
            break
        end
        inner_end = prevind(s, first(rg_close))
        body = inner_start <= inner_end ? s[inner_start:inner_end] : ""
        safe = replace(String(body), "*/" => "* /")
        write(io, "/*", safe, "*/")
        idx = nextind(s, last(rg_close))
    end
    return String(take!(io))
end

function replace_julia_ts_literals(data::AbstractString)
    data = replace(data, r"\bC_NULL\b" => "null")
    data = replace(data, r"\bnothing\b" => "null")
    data = replace(data, r"\bNothing\b" => "null")
    data = replace(data, ": null | Transform" => ": null | ITransform")
    # Drop leftover Julia type assertions in expressions, e.g. `x::Ptr{...}`.
    data = replace(data, r"::[A-Za-z_][A-Za-z0-9_\.]*(?:\{[^}]*\})?" => "")
    # Drop redundant int32 conversion helper in generated TS.
    data = replace(data, r"Math\.TypeConversions\.safe_int32_convert\(([^()]*)\)" => s"\1")
    # Julia `length(x)` -> TS `x.length` for simple non-nested args.
    data = replace(data, r"\blength\(([^()]+)\)" => s"\1.length")
    # Julia `floor(...)` -> JS `Math.floor(...)`.
    data = replace(data, r"\bfloor\(" => "Math.floor(")
    # Numeric helpers.
    data = replace(data, r"\bFloat64\(" => "Number(")
    data = replace(data, r"\binv\(([^()]+)\)" => s"(1 / (\1))")
    # Julia tuple literals in value position: `(a, b, c)` -> `[a, b, c]`.
    data = replace(data, r"=\s*\(\s*([^()\n]*,[^()\n]*)\s*\)" => s"= [\1]")
    data = replace(data, r":\s*([A-Za-z_]\w*)\s*=\s*\(\s*([^()\n]*,[^()\n]*)\s*\)" => s": \1 = [\2]")
    # Vector2f constructor calls -> plain object literals for TS compatibility.
    data = replace(data, r"\b(?:JulGame\.Math\.|Math\.)?Vector2f\(\s*([^,()]+)\s*,\s*([^()]+)\s*\)" => s"{x: \1, y: \2}")
    data = replace(data, r"\b(?:JulGame\.Math\.|Math\.)?Vector2\(\s*([^,()]+)\s*,\s*([^()]+)\s*\)" => s"{x: \1, y: \2}")
    data = replace(data, r"\b(?:JulGame\.Math\.|Math\.)?Vector3f\(\s*([^,()]+)\s*,\s*([^,()]+)\s*,\s*([^()]+)\s*\)" => s"{x: \1, y: \2, z: \3}")
    # `a && return b` is valid Julia shorthand; TS needs an explicit if.
    data = replace(data, r"(?m)^(\s*)(.+?)\s*&&\s*return\s+(.+)$" => s"\1if (\2) { return \3 }")
    # Julia try/catch forms.
    data = replace(data, r"(?m)^(\s*)try\s*$" => s"\1try {")
    data = replace(data, r"(?m)^(\s*)catch\s+([A-Za-z_]\w*)\s*$" => s"\1} catch (\2) {")
    # Local typed assignment `x::T = ...` -> `let x = ...`.
    data = replace(data, r"(?m)^(\s*)([A-Za-z_]\w*)::[^\s=]+\s*=\s*(.+)$" => s"\1let \2 = \3")
    # Ref cell reads in Julia (`x[]`) become plain property/value access.
    data = replace(data, r"\.r\[\]" => ".r")
    data = replace(data, r"\.g\[\]" => ".g")
    data = replace(data, r"\.b\[\]" => ".b")
    data = replace(data, r"\.a\[\]" => ".a")
    # SDL2 direct calls -> wasm glue calls.
    data = rewrite_sdl_calls_to_glue(data)
    # Common value-shape cleanup.
    data = replace(data, r"let center_world\s*=\s*center_pixels\s*/\s*pixels_per_world_unit\(this\)" => "let center_world = {x: center_pixels.x / pixels_per_world_unit(this), y: center_pixels.y / pixels_per_world_unit(this)}")
    data = replace(data, r"(?m)^(\s*)targetPos\s*=\s*" => s"\1let targetPos = ")
    data = replace(data, r"(?m)^(\s*)targetScale\s*=\s*" => s"\1let targetScale = ")
    data = replace(data, r"\bsetfield\(([^,]+),\s*([^,]+),\s*([^)]+)\)" => s"(\1 as any)[\2 as any] = \3")
    # `@warn "msg"` — string literal only (no interpolated/extra kwargs on this pass).
    data = replace(data, r"@warn\s+\"([^\"]*)\"" => s"console.warn(\"\1\")")
    # error with string literal
    data = replace(data, r"@error\s+\"([^\"]*)\"" => s"console.error(\"\1\")")
    # debug with string literal
    data = replace(data, r"@debug\s+\"([^\"]*)\"" => s"console.debug(\"\1\")")
    # macro invocation style: `@debug("...")`.
    data = replace(data, r"@debug\(" => "console.debug(")
    data = replace(data, r"\bprintln\(" => "console.log(")
    # info with string literal
    data = replace(data, r"@info\s+\"([^\"]*)\"" => s"console.info(\"\1\")")
    return data
end

function normalize_julgame_global_access(data::AbstractString)::String
    s = String(data)
    # Cleanup old alias-based rewrites from previous converter versions.
    s = replace(s, r"(?m)^var JG = \(globalThis as any\)\.JulGame;\s*\n?" => "")
    s = replace(s, "JG." => "(globalThis as any).JulGame.")
    occursin("JulGame.", s) || return s
    s = replace(s, "JulGame." => "(globalThis as any).JulGame.")
    return s
end

function rewrite_sdl_calls_to_glue(data::AbstractString)::String
    s = String(data)
    # Base mapping: SDL2.SDL_Foo(...) -> JulGameSdl.glue_SDL_Foo(...)
    s = replace(s, r"\bSDL2\.SDL_([A-Za-z0-9_]+)\(" => s"(globalThis as any).JulGameSdl.glue_SDL_\1(")
    # Drop renderer ptr first-arg for calls now routed to glue.
    s = replace(s, r"\b(glue_SDL_[A-Za-z0-9_]+)\(\s*(?:Renderer|\(globalThis as any\)\.JulGame\.Renderer)\s*,\s*" => s"\1(")
    # Flatten SDL_FRect wrapper when used as arg.
    s = replace(s, r"Ref\(SDL2\.SDL_FRect\(([^,]+),\s*([^,]+),\s*([^,]+),\s*([^)]+)\)\)" => s"\1, \2, \3, \4")
    # Normalize Julia 1-based indexing to TS 0-based for any numeric index.
    s = rewrite_one_based_indices(s)
    # Remove temporary color snapshot logic.
    s = replace(s, r"(?m)^\s*(?:\(globalThis as any\)\.JulGameSdl\.)?glue_SDL_GetRenderDrawColor\([^\n]*\)\s*$" => "")
    s = replace(s, r"(?m)^\s*(?:\(globalThis as any\)\.JulGameSdl\.)?glue_SDL_SetRenderDrawColor\(\s*rgba\.r\s*,\s*rgba\.g\s*,\s*rgba\.b\s*,\s*rgba\.a\s*\)\s*;?\s*$" => "")
    s = replace(s, r"(?m)^\s*let rgba = .*Ref\(UInt8\(.*\)\).*\s*$" => "")
    # RenderDrawBlendMode variant currently modeled as blend-only glue.
    s = replace(s, r"(?m)^\s*\(globalThis as any\)\.JulGameSdl\.glue_SDL_SetRenderDrawBlendMode\([^\n]*\)\s*$" => "(globalThis as any).JulGameSdl.glue_SDL_SetRenderDrawBlendMode_BLEND()")
    return s
end

function replace_setfield_calls(data::AbstractString)::String
    s = String(data)
    s = replace(s, r"\bsetfield\(\s*this\s*,\s*([A-Za-z_]\w*)\s*,\s*([^)]+)\)" => s"(this as any)[\1 as any] = \2")
    return s
end

function rewrite_one_based_indices(s::AbstractString)::String
    text = String(s)
    pat = r"\b([A-Za-z_][A-Za-z0-9_\.]*)\[(\d+)\]"
    io = IOBuffer()
    idx = firstindex(text)
    n = lastindex(text)
    while idx <= n
        rg = findnext(pat, text, idx)
        if rg === nothing
            write(io, SubString(text, idx))
            break
        end
        f = first(rg)
        f > idx && write(io, SubString(text, idx, prevind(text, f)))
        m = match(pat, text, f)
        m === nothing && break
        base = String(m[1])
        parsed = tryparse(Int, String(m[2]))
        if parsed === nothing || parsed < 1
            write(io, String(m.match))
        else
            write(io, string(base, "[", parsed - 1, "]"))
        end
        idx = nextind(text, last(rg))
    end
    return String(take!(io))
end

# Avoid collision with DOM/Web Animation types in TS output.
function replace_animation_symbol(data::AbstractString)::String
    s = String(data)
    s = replace(s, r"\bclass\s+Animation\b" => "class JulGameAnimation")
    s = replace(s, r"\bAnimation\[\]" => "JulGameAnimation[]")
    s = replace(s, r"\bAnimation\(" => "JulGameAnimation(")
    return s
end

function replace_imports_usings_includes(data::AbstractString)
    # Comment-out `using` lines; `\1` is the captured match (SubstitutionString).
    data = replace(data, r"(using .*)" => s"// \1")
    data = replace(data, r"(import .*)" => s"// \1")
    return data
end

function replace_mutable_structs(data::AbstractString)
    # `mutable struct Name` / `mutable struct Name <: Base` -> TS class (+ optional extends)
    data = replace(
        data,
        r"mutable struct\s+(\w+)\s*<:\s*([A-Za-z_][\w\.]*)" => s"class \1 extends \2 {",
    )
    data = replace(data, r"mutable struct\s+(\w+)" => s"class \1 {")
    return data
end

function replace_structs(data::AbstractString)
    # `struct Name` / `struct Name <: Base` -> TS class (+ optional extends)
    data = replace(
        data,
        r"struct\s+(\w+)\s*<:\s*([A-Za-z_][\w\.]*)" => s"class \1 extends \2 {",
    )
    data = replace(data, r"struct\s+(\w+)" => s"class \1 {")
    return data
end

# Split by commas at top level, ignoring commas inside `{...}`.
function split_top_level_commas(s::AbstractString)::Vector{String}
    out = String[]
    part = IOBuffer()
    depth = 0
    for c in String(s)
        if c == '{'
            depth += 1
            write(part, c)
        elseif c == '}'
            depth -= 1
            write(part, c)
        elseif c == ',' && depth == 0
            push!(out, strip(String(take!(part))))
        else
            write(part, c)
        end
    end
    push!(out, strip(String(take!(part))))
    return out
end

function scalar_type_to_ts(t::AbstractString, scalar_map::Dict{String,String})::String
    t = String(strip(t))
    t == "Ptr{Nothing}" && return "null"
    if startswith(t, "Vector{") && endswith(t, "}")
        inner = t[nextind(t, firstindex(t), 7):prevind(t, lastindex(t))]
        return vector_inner_to_ts(inner, scalar_map)
    end
    if haskey(scalar_map, t)
        return scalar_map[t]
    end
    if occursin('.', t)
        leaf = String(split(t, '.')[end])
        return string(get(scalar_map, leaf, leaf))
    end
    return string(get(scalar_map, t, t))
end

# `::Union{A, B, Ptr{Nothing}}` → `: A | B | null` (brace-balanced).
function replace_union_annotations(data::AbstractString, scalar_map::Dict{String,String})::String
    s = String(data)
    needle = "::Union{"
    io = IOBuffer()
    idx = firstindex(s)
    n = lastindex(s)
    while idx <= n
        rg = findnext(needle, s, idx)
        if rg === nothing
            write(io, SubString(s, idx))
            break
        end
        lo = first(rg)
        brace_open = last(rg)
        lo > idx && write(io, SubString(s, idx, prevind(s, lo)))
        depth = 1
        p = nextind(s, brace_open)
        while p <= n && depth > 0
            c = s[p]
            if c == '{'
                depth += 1
            elseif c == '}'
                depth -= 1
            end
            p = nextind(s, p)
        end
        union_inner = s[nextind(s, brace_open):prevind(s, prevind(s, p))]
        members = split_top_level_commas(union_inner)
        ts_members = map(m -> scalar_type_to_ts(m, scalar_map), members)
        write(io, ": ", join(ts_members, " | "))
        idx = p
    end
    return String(take!(io))
end

function vector_inner_to_ts(inner::AbstractString, scalar_map::Dict{String,String})::String
    inner = String(strip(inner))
    if haskey(scalar_map, inner)
        return scalar_map[inner] * "[]"
    end
    if occursin('.', inner)
        leaf = String(split(inner, '.')[end])
        return string(get(scalar_map, leaf, leaf)) * "[]"
    end
    return string(get(scalar_map, inner, inner)) * "[]"
end

function julia_type_expr_to_ts(t::AbstractString, scalar_map::Dict{String,String})::String
    t = String(strip(t))
    t == "Ptr{Nothing}" && return "null"
    t == "Nothing" && return "null"
    startswith(t, "Vector{") && endswith(t, "}") && return vector_inner_to_ts(t[nextind(t, firstindex(t), 7):prevind(t, lastindex(t))], scalar_map)
    if startswith(t, "Union{") && endswith(t, "}")
        inner = t[nextind(t, firstindex(t), 6):prevind(t, lastindex(t))]
        members = split_top_level_commas(inner)
        return join(map(m -> julia_type_expr_to_ts(m, scalar_map), members), " | ")
    end
    if startswith(t, "NTuple{") && endswith(t, "}")
        inner = t[nextind(t, firstindex(t), 7):prevind(t, lastindex(t))]
        parts = split_top_level_commas(inner)
        if length(parts) == 2
            n = tryparse(Int, strip(parts[1]))
            item_ts = julia_type_expr_to_ts(parts[2], scalar_map)
            n !== nothing && n >= 1 && n <= 16 && return "[" * join(fill(item_ts, n), ", ") * "]"
            return item_ts * "[]"
        end
    end
    if haskey(scalar_map, t)
        return scalar_map[t]
    end
    if occursin('.', t)
        leaf = String(split(t, '.')[end])
        return string(get(scalar_map, leaf, leaf))
    end
    return string(get(scalar_map, t, t))
end

function replace_struct_field_annotations(data::AbstractString, scalar_map::Dict{String,String})::String
    lines = split(String(data), '\n'; keepempty = true)
    pat = r"^(\s*[A-Za-z_]\w*)::\s*([^\n=]+?)\s*$"
    out = map(lines) do line
        m = match(pat, line)
        m === nothing && return line
        string(m[1], ": ", julia_type_expr_to_ts(String(m[2]), scalar_map))
    end
    return join(out, '\n')
end

function replace_header_param_annotations(data::AbstractString, scalar_map::Dict{String,String})::String
    lines = split(String(data), '\n'; keepempty = true)
    header_pat = r"^(\s*(?:function\s+[^\s(]+|constructor)\s*\()([^)]*)(\).*)$"
    out = map(lines) do line
        hm = match(header_pat, line)
        hm === nothing && return line
        params = split(String(hm[2]), ',')
        rewritten = map(params) do p
            pm = match(r"^(\s*[A-Za-z_]\w*)::\s*([^=]+?)(\s*=\s*.*)?\s*$", String(p))
            pm === nothing && return p
            name = String(pm[1])
            typ = julia_type_expr_to_ts(String(pm[2]), scalar_map)
            defaultv = pm[3] === nothing ? "" : String(pm[3])
            defaultv = replace(defaultv, r"=\s*nothing\b" => "= null")
            string(name, ": ", typ, defaultv)
        end
        string(hm[1], join(rewritten, ", "), hm[3])
    end
    return join(out, '\n')
end

# `::Vector{Inner}` → `: ts[]` using scalar_map for bare names and the last segment for `Mod.Type`.
# Nested `Vector{Vector{Int}}` is not supported (single `[^}]+` capture).
function replace_vector_annotations(data::AbstractString, scalar_map::Dict{String,String})
    s = String(data)
    pat = r"::Vector\{([^}]+)\}"
    io = IOBuffer()
    idx = firstindex(s)
    n = lastindex(s)
    while idx <= n
        rg = findnext(pat, s, idx)
        if rg === nothing
            write(io, SubString(s, idx))
            break
        end
        f = first(rg)
        f > idx && write(io, SubString(s, idx, prevind(s, f)))
        m = match(pat, s, f)
        m === nothing && break
        inner = m[1]::AbstractString
        write(io, ": ", vector_inner_to_ts(inner, scalar_map))
        idx = nextind(s, last(rg))
    end
    return String(take!(io))
end

function replace_types(data::AbstractString)
    scalar_map = Dict{String,String}(
        "Int32" => "number",
        "UInt64" => "number",
        "UInt32" => "number",
        "UInt16" => "number",
        "UInt8" => "number",
        "Int64" => "number",
        "Int16" => "number",
        "Int8" => "number",
        "Float32" => "number",
        "Float64" => "number",
        "String" => "string",
        "Bool" => "boolean",
        "Symbol" => "symbol",
        "InternalAnimator" => "InternalAnimator",
        "InternalSprite" => "InternalSprite",
        "InternalShape" => "InternalShape",
        "InternalRigidbody" => "InternalRigidbody",
        "InternalSoundSource" => "InternalSoundSource",
        "InternalSprite" => "InternalSprite",
        "InternalShape" => "InternalShape",
        "InternalRigidbody" => "InternalRigidbody",
        "InternalSoundSource" => "InternalSoundSource",
        "Int" => "number",
        "Animation" => "JulGameAnimation",
        "Transform" => "ITransform",
        "Any" => "any",
    )
    data = replace_union_annotations(data, scalar_map)
    data = replace_vector_annotations(data, scalar_map)
    data = replace_struct_field_annotations(data, scalar_map)
    data = replace_header_param_annotations(data, scalar_map)
    # Longer keys first so `::Int` does not chew `::Int32` into `: number` + `32`.
    for k in sort(collect(keys(scalar_map)), by = length, rev = true)
        data = replace(data, "::$k" => ": $(scalar_map[k])")
    end
    return data
end

function replace_constructor(data::AbstractString)
    # Julia inner ctor is `function ClassName(args)` (no `{`). Only the ctor whose name
    # matches a `class Name {` in this file becomes `constructor(args)`.
    seen = Set{String}()
    for m in eachmatch(r"class\s+(\w+)\s*\{", data)
        name = m.captures[1]::AbstractString
        name in seen && continue
        push!(seen, name)
        # `name` comes from `(\w+)` on the class line — no regex metacharacters to escape.
        pat = Regex("function\\s+" * string(name) * "\\s*\\(")
        data = replace(data, pat => "constructor(")
    end
    # TS needs `{` before the body; do this line-wise so nested `)` in defaults do not break.
    lines = split(String(data), '\n'; keepempty = true)
    lines = map(lines) do line
        startswith(strip(line), "constructor(") || return line
        occursin('{', line) && return line
        return line * " {"
    end
    data = join(lines, '\n')

    data = replace(data, "this = new()" => "")
    # Only the ctor idiom `return this` on its own line — not `return this.foo`.
    data = replace(data, r"(?m)^\s*return this\s*$" => "")
    return data
end

# `function A.B.c(` → `function A_B_c(` — TS cannot use `.` in a `function` name.
# Uses `findnext` + `match` (no `replace(str, regex, f)` — that overload is newer Julia).
function replace_function_declaration_dots(data::AbstractString)
    s = String(data)
    pat = r"(?m)^(\s*function\s+)([^\s(]+)(\()"
    io = IOBuffer()
    idx = firstindex(s)
    n = lastindex(s)
    while idx <= n
        rg = findnext(pat, s, idx)
        if rg === nothing
            write(io, SubString(s, idx))
            break
        end
        f = first(rg)
        f > idx && write(io, SubString(s, idx, prevind(s, f)))
        m = match(pat, s, f)
        m === nothing && break
        write(io, string(m[1], replace(m[2], "." => "_"), m[3]))
        idx = nextind(s, last(rg))
    end
    return String(take!(io))
end

# `Component.foo(` → `Component_foo(` so calls match mangled declarations.
function replace_component_qualified_calls(data::AbstractString)
    replace(data, r"\bComponent\.(\w+)\s*\(" => s"Component_\1(")
end

function replace_function_definitions(data::AbstractString)
    data = replace(data, r"@inline\s+" => "")
    # Julia: `function qual_name(args)` then newline — no `{`. TS needs `{` on the same line.
    # Name is `[^\s(]+`; `constructor(...)` is unchanged.
    data = replace(data, r"(?m)^(\s*function\s+[^\s(]+\([^)]*\))\s*$" => s"\1 {")
    return data
end

# `for x in xs` → `for (const x of xs) {` (line-wise; body closing stays `}` from Julia `end`).
function replace_for_in_loops(data::AbstractString)::String
    lines = split(String(data), '\n'; keepempty = true)
    pat = r"^(\s*)for\s+([A-Za-z_]\w*)\s+in\s+(.+)$"
    out = map(lines) do line
        m = match(pat, line)
        m === nothing && return line
        string(m[1], "for (const ", m[2], " of ", strip(String(m[3])), ") {")
    end
    return join(out, '\n')
end

function replace_if_statements(data::AbstractString)
    # Julia: `if cond` then newline — TS: `if (cond) {`. Single-line condition only; else/elseif later.
    s = String(data)
    lines = split(s, '\n'; keepempty = true)
    done_line = r"^\s*if\s*\([^)]*\)\s*\{\s*$"
    pat = r"^(\s*)if\b\s+(.+)$"
    return join(
        map(lines) do line
            occursin(done_line, line) && return line
            m = match(pat, line)
            m === nothing ? line : string(m[1], "if (", strip(m[2]), ") {")
        end,
        '\n',
    )
end

function replace_first_assignments_with_let(data::AbstractString)::String
    lines = split(String(data), '\n'; keepempty = true)
    seen = Set{String}()
    pat = r"^(\s*)([A-Za-z_]\w*)\s*=\s*(.+)$"
    header_pat = r"^\s*(?:function\s+[^\s(]+|constructor)\s*\(([^)]*)\)"
    out = map(lines) do line
        hm = match(header_pat, line)
        if hm !== nothing
            params = split(String(hm[1]), ',')
            for p in params
                pm = match(r"^\s*([A-Za-z_]\w*)", p)
                pm === nothing && continue
                push!(seen, String(pm[1]))
            end
            return line
        end
        m = match(pat, line)
        m === nothing && return line
        indent = String(m[1])
        name = String(m[2])
        rhs = String(m[3])
        # Skip obvious non-declarations / already-TS declarations.
        startswith(rhs, "=") && return line  # `==`, `===`
        startswith(rhs, ">") && return line  # `=>`
        startswith(rhs, "<") && return line  # `=<` / malformed cases
        startswith(name, "this") && return line
        if name in seen
            return line
        end
        push!(seen, name)
        return string(indent, "let ", name, " = ", rhs)
    end
    return join(out, '\n')
end

