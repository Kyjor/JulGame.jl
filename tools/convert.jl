function _try_findfirst_equality_to_ts(inner::AbstractString)::Union{Nothing,String}
    parts = split_top_level_commas_general(String(inner))
    length(parts) != 2 && return nothing
    pred = String(strip(parts[1]))
    coll = String(strip(parts[2]))
    pm = match(r"^([A-Za-z_]\w*)\s*(?:->|=>)\s*\1\s*(===|==)\s*(.+)$"s, pred)
    pm === nothing && return nothing
    lam = String(pm.captures[1])
    rhs = String(strip(String(pm.captures[3])))
    return string(
        "(() => { const a = ",
        coll,
        "; const i = a.findIndex((",
        lam,
        ") => ",
        lam,
        " === ",
        rhs,
        "); return i < 0 ? null : i + 1; })()",
    )
end

function _try_deleteat_findfirst_combo(arr::AbstractString, idxcall::AbstractString)::Union{Nothing,String}
    inner = _julia_call_paren_inner(idxcall, "findfirst(")
    inner === nothing && return nothing
    parts = split_top_level_commas_general(inner)
    length(parts) != 2 && return nothing
    pred = String(strip(parts[1]))
    coll = String(strip(parts[2]))
    pm = match(r"^([A-Za-z_]\w*)\s*(?:->|=>)\s*\1\s*(===|==)\s*(.+)$"s, pred)
    pm === nothing && return nothing
    lam = String(pm.captures[1])
    rhs = String(strip(String(pm.captures[3])))
    # `findIndex` on the same array we splice (Julia always uses one collection here).
    return string(
        "(() => { const a = ",
        arr,
        "; const i = a.findIndex((",
        lam,
        ") => ",
        lam,
        " === ",
        rhs,
        "); if (i >= 0) a.splice(i, 1); })()",
    )
end

function _parse_julia_int_underscore(s::AbstractString)::Union{Nothing,Int}
    st = String(strip(s))
    occursin(r"^[\d_]+$", st) || return nothing
    return parse(Int, replace(st, '_' => ""))
end

function _try_deleteat_simple(arr::AbstractString, idx::AbstractString)::Union{Nothing,String}
    idxt = String(strip(idx))
    length(split_top_level_commas_general(idxt)) != 1 && return nothing
    occursin(r"^\s*findfirst\s*\(", idxt) && return nothing
    rm = match(r"^([\d_]+)\s*:\s*([\d_]+)$", idxt)
    if rm !== nothing
        a = _parse_julia_int_underscore(String(rm.captures[1]))
        b = _parse_julia_int_underscore(String(rm.captures[2]))
        (a === nothing || b === nothing) && return nothing
        return string("(", arr, ").splice(", a - 1, ", ", b - a + 1, ")")
    end
    return string("(", arr, ").splice((", idxt, ") - 1, 1)")
end

"""`deleteat!(a, i)` / `deleteat(a, i)` → `splice` (1-based Julia index); combo with `findfirst(x -> x == v, a)` → `findIndex` + `splice`."""
function replace_deleteat_calls(data::AbstractString)::String
    s = String(data)
    needle = "deleteat("
    buf = IOBuffer()
    seg_start = firstindex(s)
    n = lastindex(s)
    while true
        rg = findnext(needle, s, seg_start)
        if rg === nothing
            seg_start <= n && write(buf, SubString(s, seg_start))
            break
        end
        lo = first(rg)
        lo > seg_start && write(buf, SubString(s, seg_start, prevind(s, lo)))
        inner_start = nextind(s, last(rg))
        close_idx = _find_outer_push_close(s, inner_start, n)
        if close_idx === nothing
            write(buf, SubString(s, lo:n))
            break
        end
        inner = String(s[inner_start:prevind(s, close_idx)])
        parts = split_top_level_commas_general(inner)
        repl = if length(parts) == 2
            arr = String(strip(parts[1]))
            idxcall = String(strip(parts[2]))
            r = _try_deleteat_findfirst_combo(arr, idxcall)
            r === nothing ? _try_deleteat_simple(arr, idxcall) : r
        else
            nothing
        end
        if repl === nothing
            write(buf, SubString(s, lo:close_idx))
        else
            write(buf, repl)
        end
        seg_start = nextind(s, close_idx)
    end
    return String(take!(buf))
end

"""`findfirst(x -> x == y, coll)` → 1-based index or `null` (via `findIndex`)."""
function replace_findfirst_equality_calls(data::AbstractString)::String
    s = String(data)
    needle = "findfirst("
    buf = IOBuffer()
    seg_start = firstindex(s)
    n = lastindex(s)
    while true
        rg = findnext(needle, s, seg_start)
        if rg === nothing
            seg_start <= n && write(buf, SubString(s, seg_start))
            break
        end
        lo = first(rg)
        if lo > firstindex(s)
            pc = s[prevind(s, lo)]
            if isletter(pc) || pc == '_' || isdigit(pc)
                write(buf, SubString(s, seg_start:last(rg)))
                seg_start = nextind(s, last(rg))
                continue
            end
        end
        lo > seg_start && write(buf, SubString(s, seg_start, prevind(s, lo)))
        inner_start = nextind(s, last(rg))
        close_idx = _find_outer_push_close(s, inner_start, n)
        if close_idx === nothing
            write(buf, SubString(s, lo:n))
            break
        end
        inner = String(s[inner_start:prevind(s, close_idx)])
        tsx = _try_findfirst_equality_to_ts(inner)
        if tsx === nothing
            write(buf, SubString(s, lo:close_idx))
        else
            write(buf, tsx)
        end
        seg_start = nextind(s, close_idx)
    end
    return String(take!(buf))
end

function _find_outer_push_close(s::String, inner_start::Int, n::Int)::Union{Nothing, Int}
    i = inner_start
    paren = 1
    bracket = 0
    brace = 0
    while i <= n
        c = s[i]
        if c == '"'
            i = _skip_double_quoted_string(s, i, n)
            i > n && return nothing
            i = nextind(s, i)
            continue
        end
        if c == '('
            paren += 1
        elseif c == ')'
            paren -= 1
            if paren == 0
                return i
            end
        elseif c == '['
            bracket += 1
        elseif c == ']'
            bracket -= 1
        elseif c == '{'
            brace += 1
        elseif c == '}'
            brace -= 1
        end
        i = nextind(s, i)
    end
    return nothing
end

function _skip_double_quoted_string(s::String, open_quote_at::Int, n::Int)::Int
    i = nextind(s, open_quote_at)
    while i <= n
        c = s[i]
        if c == '\\'
            i = nextind(s, i)
            i = nextind(s, i)
            continue
        end
        if c == '"'
            return i
        end
        i = nextind(s, i)
    end
    return i
end

function _parse_push_two_args(s::String, inner_start::Int, n::Int)::Union{Nothing, Tuple{SubString{String}, SubString{String}, Int}}
    i = inner_start
    paren = 1
    bracket = 0
    brace = 0
    arg1_lo = i
    split_at = nothing
    while i <= n
        c = s[i]
        if c == '"'
            i = _skip_double_quoted_string(s, i, n)
            i > n && return nothing
            i = nextind(s, i)
            continue
        end
        if c == '('
            paren += 1
        elseif c == ')'
            paren -= 1
            if paren == 0
                return nothing
            end
        elseif c == '['
            bracket += 1
        elseif c == ']'
            bracket -= 1
        elseif c == '{'
            brace += 1
        elseif c == '}'
            brace -= 1
        elseif c == ',' && paren == 1 && bracket == 0 && brace == 0
            split_at = i
            break
        end
        i = nextind(s, i)
    end
    split_at === nothing && return nothing
    arg1 = SubString(s, arg1_lo, prevind(s, split_at))
    i = nextind(s, split_at)
    arg2_lo = i
    while i <= n
        c = s[i]
        if c == '"'
            i = _skip_double_quoted_string(s, i, n)
            i > n && return nothing
            i = nextind(s, i)
            continue
        end
        if c == '('
            paren += 1
        elseif c == ')'
            paren -= 1
            if paren == 0
                arg2 = SubString(s, arg2_lo, prevind(s, i))
                return (arg1, arg2, i)
            end
        elseif c == '['
            bracket += 1
        elseif c == ']'
            bracket -= 1
        elseif c == '{'
            brace += 1
        elseif c == '}'
            brace -= 1
        end
        i = nextind(s, i)
    end
    return nothing
end

function remove_!_from_function_names(data::AbstractString)
    # Julia mutating calls (`push!(x)`) only — keep TS unary `!(expr)`.
    return replace(data, r"(\w)!\(" => s"\1(")
end

function source_files_from_manifest(; repo_root::AbstractString = REPO_ROOT)::Vector{String}
    manifest = joinpath(repo_root, "ts", "files-needed.txt")
    isfile(manifest) || return String[]
    wanted = String[]
    for raw in split(read(manifest, String), '\n')
        name = strip(raw)
        isempty(name) && continue
        push!(wanted, endswith(name, ".jl") ? name : name * ".jl")
    end

    # Build basename -> absolute file map once from src/.
    by_name = Dict{String, Vector{String}}()
    src_root = joinpath(repo_root, "src")
    for (dir, _, files) in walkdir(src_root)
        for f in files
            !endswith(f, ".jl") && continue
            abs = joinpath(dir, f)
            if haskey(by_name, f)
                push!(by_name[f], abs)
            else
                by_name[f] = [abs]
            end
        end
    end

    selected = String[]
    for name in wanted
        matches = get(by_name, name, String[])
        isempty(matches) && error("files-needed entry not found in src/: $name")
        length(matches) > 1 && error("files-needed entry is ambiguous in src/: $name")
        push!(selected, first(matches))
    end
    return selected
end

# If any line of a TS `if (...) { ... }` block contains `needle`, replace the **whole** block with `value`
# (`value == ""` deletes it). Keys are plain substrings — no regex. First matching key (dict order) wins.
# Example: `TS_IF_BLOCKS_REMOVE_OR_REPLACE_WHEN_CONTAINS["haskey((globalThis as any).JulGame.AUDIO_CACHE"] = ""`
const TS_IF_BLOCKS_REMOVE_OR_REPLACE_WHEN_CONTAINS = Dict{String,String}(
    "haskey((globalThis as any).JulGame.AUDIO_CACHE" => "",
    "haskey((globalThis as any).JulGame.IMAGE_CACHE" => "",
    "usingEffectTex" => "",
    "haskey(TEXTURE_CACHE, imagePath)" => "",
    "self.texture != null && !haskey(TEXTURE_CACHE, self.imagePath)" => "",
)

function _find_ts_if_opening_brace_on_line(ln::AbstractString, cond_paren_inner_start::Int)::Union{Nothing, Int}
    s = String(ln)
    close_cond = _find_outer_push_close(s, cond_paren_inner_start, lastindex(s))
    close_cond === nothing && return nothing
    j = nextind(s, close_cond)
    n = lastindex(s)
    while j <= n
        c = s[j]
        if c == '"'
            j = _skip_double_quoted_string(s, j, n)
            j = nextind(s, j)
            continue
        end
        c == '{' && return j
        j = nextind(s, j)
    end
    return nothing
end

# Returns (start_line_idx, end_line_idx) 1-based inclusive for the `if` line through its matching closing `}`.
function _find_ts_if_block_line_range(lines::Vector{String}, start_line::Int)::Union{Nothing, Tuple{Int, Int}}
    start_line <= length(lines) || return nothing
    ln = lines[start_line]
    occursin(r"^\s*if\s*\(", ln) || return nothing
    m = match(r"^\s*if\s*\(\s*", ln)
    m === nothing && return nothing
    cond_inner = nextind(ln, lastindex(String(m.match)))
    brace_at = _find_ts_if_opening_brace_on_line(ln, cond_inner)
    brace_at === nothing && return nothing
    depth = 1
    li = start_line
    i = nextind(ln, brace_at)
    nlines = length(lines)
    while li <= nlines
        cur = lines[li]
        n = lastindex(cur)
        while i <= n
            c = cur[i]
            if c == '"'
                i = _skip_double_quoted_string(cur, i, n)
                i > n && return nothing
                i = nextind(cur, i)
                continue
            end
            if c == '{'
                depth += 1
            elseif c == '}'
                depth -= 1
                if depth == 0
                    return (start_line, li)
                end
            end
            i = nextind(cur, i)
        end
        li += 1
        li > nlines && break
        i = firstindex(lines[li])
    end
    return nothing
end

function replace_ts_if_blocks_when_block_contains_substring(data::AbstractString)::String
    isempty(TS_IF_BLOCKS_REMOVE_OR_REPLACE_WHEN_CONTAINS) && return String(data)
    lines = split(String(data), '\n'; keepempty = true)
    ls = collect(String.(lines))
    changed = true
    while changed
        changed = false
        for i in 1:length(ls)
            occursin(r"^\s*if\s*\(", ls[i]) || continue
            rg = _find_ts_if_block_line_range(ls, i)
            rg === nothing && continue
            lo, hi = rg
            block_text = join(view(ls, lo:hi), '\n')
            hit = false
            replacement = ""
            for (needle, repl) in TS_IF_BLOCKS_REMOVE_OR_REPLACE_WHEN_CONTAINS
                if occursin(needle, block_text)
                    replacement = repl
                    hit = true
                    break
                end
            end
            if !hit
                continue
            end
            rep_lines = if isempty(replacement)
                String[]
            else
                collect(String.(split(String(replacement), '\n'; keepempty = true)))
            end
            splice!(ls, lo:hi, rep_lines)
            changed = true
            break
        end
    end
    return join(ls, '\n')
end

function replace_entire_line_if_matches(data::AbstractString, path_jl::AbstractString = "")::String
    # Ordered rules: first match wins. If `needle` appears anywhere on a line, the whole line becomes `replacement`.
    line_rules = Pair{Union{String, Regex}, String}[]
    push!(line_rules, "add_observer" => "")
    push!(line_rules, "throw(" => "")
    push!(line_rules, "update_effects(" => "")
    push!(line_rules, "texture_to_render = self.effectTexture" => "")
    push!(line_rules, "show_backtrace" => "")
    push!(line_rules, "TEXTURE_CACHE[imagePath] = tex" => "")
    if !is_input_source(path_jl)
        push!(line_rules, "_input_ui_hit_span" => "")
        push!(line_rules, "_input_poll_accumulate" => "")
        push!(line_rules, "_input_ui_hit_step" => "")
        push!(line_rules, "_input_ui_hit_iter_stream_logs" => "")
        push!(line_rules, "_input_ui_hit_stream_logs" => "")
        push!(line_rules, "_handle_clipboard_paste" => "")
        push!(line_rules, "handle_dropped_files" => "")
        push!(line_rules, "is not set in the main scene" => "")
        push!(line_rules, "uiElementsOrderedByLayerDescending = sort(reverse" => "")
        push!(line_rules, "entitiesWithSpritesOrderedByLayerDescending =" => "")
        push!(
            line_rules,
            " elementsOrderedByLayerDescending = vcat" =>
                "let elementsOrderedByLayerDescending = (globalThis as any).JulGame.MAIN.scene.uiElements",
        )
    end

    lines = split(String(data), '\n'; keepempty = true)
    out = map(lines) do line
        for (needle, replacement) in line_rules
            occursin(needle, line) && return String(replacement)
        end
        line
    end
    return join(out, '\n')
end

function parse_cli_args()::Tuple{Vector{String}, AbstractString}
    project_root = nothing
    all_scripts = false
    files = String[]
    i = 1
    while i <= length(ARGS)
        a = ARGS[i]
        if a == "--project-root"
            i + 1 > length(ARGS) && error("--project-root requires a path")
            project_root = abspath(ARGS[i + 1])
            i += 2
            continue
        elseif a == "--all-scripts"
            all_scripts = true
            i += 1
            continue
        else
            base = project_root !== nothing ? project_root : REPO_ROOT
            p = isabspath(a) ? String(a) : joinpath(base, String(a))
            isfile(p) || error("not a file: $p")
            push!(files, p)
            i += 1
        end
    end
    if all_scripts
        project_root === nothing && error("--all-scripts requires --project-root")
        append!(files, collect_project_script_files(project_root))
    end
    if isempty(files)
        if project_root !== nothing
            append!(files, collect_project_script_files(project_root))
        else
            append!(files, source_files_from_manifest())
        end
    end
    isempty(files) && (files = [joinpath(REPO_ROOT, "src", "MainLoop.jl")])
    repo = project_root !== nothing ? project_root : REPO_ROOT
    return unique(files), repo
end

function main()
    files, repo_root = parse_cli_args()
    # Smallest-first helps us iterate patterns safely from simpler files upward.
    sort!(files, by = f -> filesize(f))
    mkpath(default_out_dir())
    transpiled_scripts = false
    for f in files
        isfile(f) || error("not a file: $f")
        println(transpile_file(f; repo_root = repo_root))
        transpiled_scripts |= is_game_script_source(f)
    end
    if transpiled_scripts
        idx = write_scripts_index(repo_root)
        idx !== nothing && println(idx)
    end
end

if abspath(PROGRAM_FILE) == @__FILE__
    main()
end
