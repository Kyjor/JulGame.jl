# Julia `""" ... """` docstrings → TS block comments. Run after `#` → `//` inside the doc body.
# Break `*/` in the body so the comment does not end early.
function replace_docstrings(data::AbstractString)::String
    s = String(data)
    delim = "\"\"\""
    io = IOBuffer()
    idx = firstindex(s)
    n = lastindex(s)
    while idx <= n
        rg_open = findnext(delim, s, idx)
        if rg_open === nothing
            write(io, SubString(s, idx))
            break
        end
        lo = first(rg_open)
        lo > idx && write(io, SubString(s, idx, prevind(s, lo)))
        inner_start = nextind(s, last(rg_open))
        rg_close = findnext(delim, s, inner_start)
        if rg_close === nothing
            write(io, SubString(s, idx))
            break
        end
        inner_end = prevind(s, first(rg_close))
        body = inner_start <= inner_end ? s[inner_start:inner_end] : ""
        safe = replace(String(body), "*/" => "* /")
        write(io, "/*", safe, "*/")
        idx = nextind(s, last(rg_close))
    end
    return String(take!(io))
end

# `TypeConversions.safe_int32_convert(expr)` / `Math.TypeConversions...` -> `expr` (balanced parens for nested calls).
function strip_safe_int32_convert_calls(data::AbstractString)::String
    s = String(data)
    needles = ("Math.TypeConversions.safe_int32_convert(", "TypeConversions.safe_int32_convert(")
    changed = true
    while changed
        changed = false
        fi = firstindex(s)
        n = lastindex(s)
        for needle in needles
            rg = findnext(needle, s, fi)
            rg === nothing && continue
            lo = first(rg)
            inner_start = nextind(s, last(rg))
            close_idx = _find_outer_push_close(s, inner_start, n)
            close_idx === nothing && continue
            inner = s[inner_start:prevind(s, close_idx)]
            pre = s[fi:prevind(s, lo)]
            post = s[nextind(s, close_idx):n]
            s = string(pre, inner, post)
            changed = true
            break
        end
    end
    return s
end

# `UInt32(expr)` -> `expr` when `expr` is a numeric literal; otherwise `((expr) >>> 0)` (unsigned 32-bit in JS).
function strip_uint32_constructor_calls(data::AbstractString)::String
    s = String(data)
    needle = "UInt32("
    changed = true
    while changed
        changed = false
        fi = firstindex(s)
        n = lastindex(s)
        rg = findnext(needle, s, fi)
        rg === nothing && break
        lo = first(rg)
        inner_start = nextind(s, last(rg))
        close_idx = _find_outer_push_close(s, inner_start, n)
        close_idx === nothing && break
        inner = strip(s[inner_start:prevind(s, close_idx)])
        replacement = if occursin(r"^\d+\s*$", inner)
            inner
        else
            string("((", inner, ") >>> 0)")
        end
        pre = s[fi:prevind(s, lo)]
        post = s[nextind(s, close_idx):n]
        s = string(pre, replacement, post)
        changed = true
    end
    return s
end

# Julia `return (a, b, ...)` tuple → TS `return [a, b, ...]` (comma operator is not tuple semantics).
function replace_return_parenthesized_tuples(data::AbstractString)::String
    s = String(data)
    rx = r"return\s+\("
    i = firstindex(s)
    n = lastindex(s)
    io = IOBuffer()
    while i <= n
        rg = findnext(rx, s, i)
        if rg === nothing
            write(io, SubString(s, i))
            break
        end
        lo = first(rg)
        lo > i && write(io, SubString(s, i, prevind(s, lo)))
        open_at = last(rg)
        inner_start = nextind(s, open_at)
        close_idx = _find_outer_push_close(s, inner_start, n)
        if close_idx === nothing
            write(io, SubString(s, lo))
            break
        end
        inner = s[inner_start:prevind(s, close_idx)]
        parts = split_top_level_commas_general(inner)
        if length(parts) < 2 || any(isempty(strip(p)) for p in parts)
            write(io, SubString(s, lo, close_idx))
        else
            write(io, "return [", join(parts, ", "), "]")
        end
        i = nextind(s, close_idx)
    end
    return String(take!(io))
end

# `Math.Vector2(a, b)` / `Vector3f` / `Math.Vector4(...)` — regex-only rewrite misses args that contain `(...)`; use balanced parens + top-level comma split.
function replace_math_vector_constructor_calls(data::AbstractString)::String
    needles_meta = (
        ("JulGame.Math.Vector4(", 4),
        ("JulGame.Math.Vector3f(", 3),
        ("JulGame.Math.Vector2f(", 2),
        ("JulGame.Math.Vector2(", 2),
        ("Math.Vector4(", 4),
        ("Math.Vector3f(", 3),
        ("Math.Vector2f(", 2),
        ("Math.Vector2(", 2),
        ("Vector4(", 4),
        ("Vector3f(", 3),
        ("Vector2f(", 2),
        ("Vector2(", 2),
    )
    s = String(data)
    io = IOBuffer()
    fi = firstindex(s)
    n = lastindex(s)
    while fi <= n
        best_lo = nothing
        best_hi = nothing
        best_arity = 2
        for (needle, arity) in needles_meta
            rg = findnext(needle, s, fi)
            rg === nothing && continue
            lo = first(rg)
            if best_lo === nothing || lo < best_lo
                best_lo = lo
                best_hi = last(rg)
                best_arity = arity
            end
        end
        if best_lo === nothing
            write(io, SubString(s, fi))
            break
        end
        best_lo > fi && write(io, SubString(s, fi, prevind(s, best_lo)))
        inner_start = nextind(s, best_hi)
        close_idx = _find_outer_push_close(s, inner_start, n)
        if close_idx === nothing
            write(io, SubString(s, best_lo))
            break
        end
        inner = s[inner_start:prevind(s, close_idx)]
        parts = split_top_level_commas_general(inner)
        if length(parts) == best_arity
            if best_arity == 2
                write(io, "{x: ", parts[1], ", y: ", parts[2], "}")
            elseif best_arity == 3
                write(io, "{x: ", parts[1], ", y: ", parts[2], ", z: ", parts[3], "}")
            else
                write(io, "{x: ", parts[1], ", y: ", parts[2], ", z: ", parts[3], ", t: ", parts[4], "}")
            end
        else
            write(io, SubString(s, best_lo, close_idx))
        end
        fi = nextind(s, close_idx)
    end
    return String(take!(io))
end

# `{` at `open_brace_at` must be the opening `{` of an object literal.
function _find_matching_brace_close(s::String, open_brace_at::Int, n::Int)::Union{Nothing, Int}
    depth = 0
    i = open_brace_at
    while i <= n
        c = s[i]
        if c == '"'
            i = _skip_double_quoted_string(s, i, n)
            i > n && return nothing
            i = nextind(s, i)
            continue
        end
        if c == '{'
            depth += 1
        elseif c == '}'
            depth -= 1
            if depth == 0
                return i
            end
        end
        i = nextind(s, i)
    end
    return nothing
end

function _parse_ts_vector_object_key_vals(inner::AbstractString)::Union{Nothing,Dict{String,String}}
    parts = split_top_level_commas_general(inner)
    d = Dict{String,String}()
    for p in parts
        m = match(r"^\s*([A-Za-z_]\w*)\s*:\s*(.+)$"s, strip(String(p)))
        m === nothing && return nothing
        d[String(m[1])] = String(strip(String(m[2])))
    end
    return d
end

# Recognizes `{x,y}`, `{x,y,z}`, `{x,y,z,t}` from emitted vector ctor literals (exact key sets).
function _parse_vector234_object_fields(inner::AbstractString)::Union{Nothing,Tuple{Int,Vector{String}}}
    d = _parse_ts_vector_object_key_vals(inner)
    d === nothing && return nothing
    nkeys = length(d)
    if haskey(d, "t")
        if nkeys == 4 && haskey(d, "x") && haskey(d, "y") && haskey(d, "z")
            return (4, [d["x"], d["y"], d["z"], d["t"]])
        end
        return nothing
    elseif haskey(d, "z")
        if nkeys == 3 && haskey(d, "x") && haskey(d, "y")
            return (3, [d["x"], d["y"], d["z"]])
        end
        return nothing
    elseif haskey(d, "y")
        if nkeys == 2 && haskey(d, "x")
            return (2, [d["x"], d["y"]])
        end
        return nothing
    end
    return nothing
end

function _ts_vector_literal_field_eq_checks(lhs::AbstractString, vals::Vector{String}, arity::Int)::String
    if arity == 2
        return "$(lhs).x === $(vals[1]) && $(lhs).y === $(vals[2])"
    elseif arity == 3
        return "$(lhs).x === $(vals[1]) && $(lhs).y === $(vals[2]) && $(lhs).z === $(vals[3])"
    else
        return "$(lhs).x === $(vals[1]) && $(lhs).y === $(vals[2]) && $(lhs).z === $(vals[3]) && $(lhs).t === $(vals[4])"
    end
end

function _ts_vector_literal_eq_replacement(lhs::AbstractString, vals::Vector{String}, arity::Int)::String
    checks = _ts_vector_literal_field_eq_checks(lhs, vals, arity)
    return "$(lhs) != null && $(checks)"
end

function _ts_vector_literal_eq_or_null_replacement(lhs::AbstractString, vals::Vector{String}, arity::Int)::String
    checks = _ts_vector_literal_field_eq_checks(lhs, vals, arity)
    return "$(lhs) === null || ($(checks))"
end

function _ts_vector_literal_ne_replacement(lhs::AbstractString, vals::Vector{String}, arity::Int)::String
    parts = String["$(lhs) == null"]
    if arity == 2
        push!(parts, "$(lhs).x !== $(vals[1])", "$(lhs).y !== $(vals[2])")
    elseif arity == 3
        push!(parts, "$(lhs).x !== $(vals[1])", "$(lhs).y !== $(vals[2])", "$(lhs).z !== $(vals[3])")
    else
        push!(
            parts,
            "$(lhs).x !== $(vals[1])",
            "$(lhs).y !== $(vals[2])",
            "$(lhs).z !== $(vals[3])",
            "$(lhs).t !== $(vals[4])",
        )
    end
    return "(" * join(parts, " || ") * ")"
end

# Slice `[lhs_start:lhs_end]` for `foo.bar` / `self.crop` immediately before `\s*==\s*\{` / `\s*!=\s*\{`.
function _ts_simple_lhs_span(s::String, i::Int, eq_ne_match_lo::Int)::Union{Nothing,Tuple{Int,Int}}
    j = prevind(s, eq_ne_match_lo)
    while j >= i && isspace(s[j])
        j = prevind(s, j)
    end
    j < i && return nothing
    lhs_end = j
    k = lhs_end
    while k >= i
        c = s[k]
        if isletter(c) || isdigit(c) || c == '_' || c == '.'
            k = prevind(s, k)
            continue
        end
        break
    end
    lhs_start = nextind(s, k)
    lhs_start > lhs_end && return nothing
    return (lhs_start, lhs_end)
end

# JS compares objects by reference — `{x:0,...}` literals never `==` or `!=` an existing object sensibly.
# Rewrite comparisons against emitted `{x,y(,z(,t))}` literals to field-wise checks (after vector ctor rewrite).
function replace_ts_vector_object_literal_equality(data::AbstractString)::String
    s = String(data)
    i = firstindex(s)
    n = lastindex(s)
    io = IOBuffer()
    while i <= n
        r_eq = findnext(" == {", s, i)
        r_ne = findnext(" != {", s, i)
        r = nothing
        op_is_ne = false
        if r_eq !== nothing && r_ne !== nothing
            if first(r_eq) <= first(r_ne)
                r = r_eq
                op_is_ne = false
            else
                r = r_ne
                op_is_ne = true
            end
        elseif r_eq !== nothing
            r = r_eq
            op_is_ne = false
        elseif r_ne !== nothing
            r = r_ne
            op_is_ne = true
        else
            write(io, SubString(s, i))
            break
        end
        lo = first(r)
        open_brace = last(r)
        close_idx = _find_matching_brace_close(s, open_brace, n)
        if close_idx === nothing
            write(io, SubString(s, i, lo))
            i = nextind(s, lo)
            continue
        end
        inner = String(SubString(s, nextind(s, open_brace), prevind(s, close_idx)))
        parsed = _parse_vector234_object_fields(inner)
        span = _ts_simple_lhs_span(s, i, lo)
        if parsed === nothing || span === nothing
            write(io, SubString(s, i, close_idx))
            i = nextind(s, close_idx)
            continue
        end
        lhs_start, lhs_end = span
        lhs = String(SubString(s, lhs_start, lhs_end))
        arity, vals = parsed
        m_or = nothing
        repl =
            if op_is_ne
                _ts_vector_literal_ne_replacement(lhs, vals, arity)
            else
                tail_str = String(SubString(s, nextind(s, close_idx), n))
                m_or = match(r"^\s*\|\|\s*(.+?)\s*===?\s*null\b", tail_str)
                if m_or !== nothing && strip(String(m_or[1])) == lhs
                    _ts_vector_literal_eq_or_null_replacement(lhs, vals, arity)
                else
                    _ts_vector_literal_eq_replacement(lhs, vals, arity)
                end
            end
        write(io, SubString(s, i, prevind(s, lhs_start)))
        write(io, repl)
        if !op_is_ne && m_or !== nothing && strip(String(m_or[1])) == lhs
            pos = nextind(s, close_idx)
            for _ in m_or.match
                pos = nextind(s, pos)
            end
            i = pos
        else
            i = nextind(s, close_idx)
        end
    end
    return String(take!(io))
end

# `Dict{K,V}()` / `Dict{K, glue_T}()` (after SDL rewrites in type position) → `{}` for empty Julia dict init.
function replace_julia_dict_empty_ctor_as_object(data::AbstractString)::String
    s = String(data)
    out = IOBuffer()
    i = firstindex(s)
    n = lastindex(s)
    needle = "Dict{"
    while i <= n
        rg = findnext(needle, s, i)
        if rg === nothing
            write(out, SubString(s, i:n))
            break
        end
        lo = first(rg)
        lo > i && write(out, SubString(s, i, prevind(s, lo)))
        open_brace = last(rg)
        depth = 1
        p = nextind(s, open_brace)
        close_br = nothing
        while p <= n
            c = s[p]
            if c == '{'
                depth += 1
            elseif c == '}'
                depth -= 1
                if depth == 0
                    close_br = p
                    break
                end
            end
            p = nextind(s, p)
        end
        if close_br === nothing
            write(out, SubString(s, lo))
            i = nextind(s, lo)
            continue
        end
        nxt = nextind(s, close_br)
        if nxt <= n && s[nxt] == '('
            inner_start = nextind(s, nxt)
            close_paren = _find_outer_push_close(s, inner_start, n)
            if close_paren !== nothing
                write(out, "{}")
                i = nextind(s, close_paren)
                continue
            end
        end
        write(out, SubString(s, lo:close_br))
        i = nextind(s, close_br)
    end
    return String(take!(out))
end

# Julia `SubString(s, i, j)` (1-based inclusive end `j`) → TS `s.slice(i - 1, j)` (`slice` end is exclusive; matches Julia end-inclusive).
function replace_julia_substring_three_arg_calls(data::AbstractString)::String
    s = String(data)
    out = IOBuffer()
    i = firstindex(s)
    n = lastindex(s)
    pat = r"\bSubString\("
    while i <= n
        rg = findnext(pat, s, i)
        if rg === nothing
            write(out, SubString(s, i:n))
            break
        end
        lo = first(rg)
        lo > i && write(out, SubString(s, i, prevind(s, lo)))
        inner_start = nextind(s, last(rg))
        close_idx = _find_outer_push_close(s, inner_start, n)
        if close_idx === nothing
            write(out, SubString(s, lo))
            i = nextind(s, lo)
            continue
        end
        inner = String(SubString(s, inner_start, prevind(s, close_idx)))
        parts = split_top_level_commas_general(inner)
        if length(parts) != 3
            write(out, SubString(s, lo:close_idx))
            i = nextind(s, close_idx)
            continue
        end
        a = String(strip(parts[1]))
        b = String(strip(parts[2]))
        c = String(strip(parts[3]))
        write(out, "(", a, ").slice((", b, ") - 1, ", c, ")")
        i = nextind(s, close_idx)
    end
    return String(take!(out))
end

function replace_julia_ts_literals(data::AbstractString)
    data = replace(data, r"\bC_NULL\b" => "null")
    data = replace(data, r"\bnothing\b" => "null")
    # `w, h = Ref{Cint}(0), Ref{Cint}(0)` → `let w = [0], h = [0]`.
    data = replace(
        data,
        r"(?m)^(\s*)([A-Za-z_]\w*)\s*,\s*([A-Za-z_]\w*)\s*=\s*Ref\{Cint\}\(\s*([^)]*)\s*\)\s*,\s*Ref\{Cint\}\(\s*([^)]*)\s*\)\s*;?\s*$" =>
            s"\1let \2 = [\4], \3 = [\5]",
    )
    # `const _trace_… = Ref{Union{…}}(null)` → plain nullable flag (no `Ref` in TS).
    data = replace(
        data,
        r"^\s*const\s+(_trace_input_ui_hit_iter_ref)\s*=\s*Ref\{Union\{[^}]+\}\}\(\s*null\s*\)\s*;?\s*$"m =>
            s"    let \1: boolean | null = null",
    )
    data = replace(data, r"\bNothing\b" => "null")
    data = replace(data, ": null | Transform" => ": null | ITransform")
    # Drop leftover Julia type assertions in expressions, e.g. `x::Ptr{...}`.
    data = replace(data, r"::[A-Za-z_][A-Za-z0-9_\.]*(?:\{[^}]*\})?" => "")
    # Drop redundant int32 conversion helper in generated TS (any nesting).
    data = strip_safe_int32_convert_calls(data)
    data = strip_uint32_constructor_calls(data)
    # `UInt8(n)` / `UInt8(expr)` — same idea as UInt32 (SDL color components).
    data = replace(data, r"\bUInt8\(\s*(\d+)\s*\)" => s"\1")
    data = replace(data, r"\bUInt8\(" => "Number(")
    data = replace(data, r"\bInt32\(\s*(\d+)\s*\)" => s"\1")
    data = replace(data, r"\bInt32\(" => "Number(")
    # Julia typed vector literal `Int32[0, 1]` → TS `[0, 1]` (also used as int out-param buffers).
    data = replace(data, r"\bInt32\[" => "[")
    data = replace(data, r"\bUInt64\(\s*(\d+)\s*\)" => s"\1")
    data = replace(data, r"\bUInt64\(" => "Number(")
    # Julia `length(x)` -> TS `x.length` for simple non-nested args.
    data = replace(data, r"\blength\(([^()]+)\)" => s"\1.length")
    # Julia `floor(T, x)` / `round(T, x)` / `ceil(T, x)` (T an integer type) → JS `Math.*(x)`.
    _jint = "(?:Int|Int32|Int64|UInt32|UInt64|Integer)"
    data = replace(data, Regex("\\bfloor\\s*\\(\\s*" * _jint * "\\s*,\\s*") => "Math.floor(")
    data = replace(data, Regex("\\bround\\s*\\(\\s*" * _jint * "\\s*,\\s*") => "Math.round(")
    data = replace(data, Regex("\\bceil\\s*\\(\\s*" * _jint * "\\s*,\\s*") => "Math.ceil(")
    # Julia `floor(x)` -> JS `Math.floor(x)` (skip if already `Math.floor`).
    data = replace(data, r"(?<!\bMath\.)\bfloor\(" => "Math.floor(")
    # Julia enum helper `instances(T)` -> JS value iteration.
    data = replace(data, r"\binstances\(" => "Object.values(")
    # Julia `min(...)` -> JS `Math.min(...)` (not `Math.Math.min` — exclude already-prefixed).
    data = replace(data, r"(?<!\bMath\.)\bmin\s*\(" => "Math.min(")
    data = replace(data, r"(?<!\bMath\.)\bmax\s*\(" => "Math.max(")
    # Bare `round(...)` -> `Math.round(...)` (word + call only; not `Math.round`, `surround`, etc.).
    data = replace(data, r"(?<!\bMath\.)\bround\s*\(" => "Math.round(")
    # Bare `ceil(...)` -> `Math.ceil(...)`.
    data = replace(data, r"(?<!\bMath\.)\bceil\(" => "Math.ceil(")
    # `clamp(...)` stays as `clamp(...)`; generated files import it from `juliaHelpers.ts`.
    # Numeric helpers.
    # Julia `Inf` / `-Inf` → JS `Infinity` / `-Infinity`.
    data = replace(data, r"\bInf\b" => "Infinity")
    data = replace(data, r"\bFloat64\(" => "Number(")
    data = replace(data, r"\bFloat32\(" => "Number(")
    # `convert(Float64, x)` (no global `convert` in JS) — same intent as `Float64(x)`.
    data = replace(data, r"\bconvert\s*\(\s*Float64\s*,\s*" => "Number(")
    data = replace(data, r"\binv\(([^()]+)\)" => s"(1 / (\1))")
    # Julia tuple literals in value position: `(a, b, c)` -> `[a, b, c]`.
    data = replace(data, r"=\s*\(\s*([^()\n]*,[^()\n]*)\s*\)" => s"= [\1]")
    data = replace(data, r":\s*([A-Za-z_]\w*)\s*=\s*\(\s*([^()\n]*,[^()\n]*)\s*\)" => s": \1 = [\2]")
    # Vector2 / Vector2f / Vector3f / Vector4 constructor calls -> `{ x, y [, z [, t]] }` (handles nested parens in arguments).
    data = replace_math_vector_constructor_calls(data)
    # Rigidbody: grounded snap keeps `z` (integrated position may be Vector2f with no z).
    data = replace(
        data,
        "newPosition = {x: newPosition.x, y: currentPosition.y}" =>
            "newPosition = {x: newPosition.x, y: currentPosition.y, z: newPosition.z ?? currentPosition.z ?? 0}",
    )
    # `a && return b` is valid Julia shorthand; TS needs an explicit if.
    data = replace(data, r"(?m)^(\s*)(.+?)\s*&&\s*return\s+(.+)$" => s"\1if (\2) { return \3 }")
    data = replace_return_parenthesized_tuples(data)
    # Julia try/catch forms.
    data = replace(data, r"(?m)^(\s*)try\s*$" => s"\1try {")
    data = replace(data, r"(?m)^(\s*)catch\s+([A-Za-z_]\w*)\s*$" => s"\1} catch (\2) {")
    data = replace(data, r"(?m)^(\s*)catch\s*$" => s"\1} catch {")
    # Julia lambdas `x -> expr` → TS `x => expr` (repeat: nested `f->f==` etc.).
    for _ in 1:64
        old = data
        data = replace(data, r"\b([A-Za-z_]\w*)\s*->\s*" => s"\1 => ")
        old == data && break
    end
    # Local typed assignment `x::T = ...` -> `let x = ...`.
    data = replace(data, r"(?m)^(\s*)([A-Za-z_]\w*)::[^\s=]+\s*=\s*(.+)$" => s"\1let \2 = \3")
    # Ref cell reads in Julia (`x[]`) become plain property/value access.
    data = replace(data, r"\.r\[\]" => ".r")
    data = replace(data, r"\.g\[\]" => ".g")
    data = replace(data, r"\.b\[\]" => ".b")
    data = replace(data, r"\.a\[\]" => ".a")
    # SDL2 direct calls -> wasm glue calls.
    data = rewrite_sdl_calls_to_glue(data)
    # `SDL_GetMouseState` out ints: Julia `pointer(x)` on `Int32[...]` buffers → glue `...x, ...y` (same idea as color ref spreads).
    data = replace(
        data,
        r"\.glue_SDL_GetMouseState\(\s*pointer\(\s*([A-Za-z_]\w*)\s*\)\s*,\s*pointer\(\s*([A-Za-z_]\w*)\s*\)\)" =>
            s".glue_SDL_GetMouseState(...\1, ...\2)",
    )
    data = replace(
        data,
        r"\.glue_SDL_GetMouseState\(\s*([A-Za-z_]\w*)\s*,\s*([A-Za-z_]\w*)\s*\)" =>
            s".glue_SDL_GetMouseState(...\1, ...\2)",
    )
    data = replace(
        data,
        r"\.glue_SDL_GetWindowSize\(\s*([^,]+?)\s*,\s*([A-Za-z_]\w*)\s*,\s*([A-Za-z_]\w*)\s*\)" =>
            s".glue_SDL_GetWindowSize(\1, ...\2, ...\3)",
    )
    data = replace(
        data,
        r"\.glue_SDL_GetWindowPosition\(\s*([^,]+?)\s*,\s*([A-Za-z_]\w*)\s*,\s*([A-Za-z_]\w*)\s*\)" =>
            s".glue_SDL_GetWindowPosition(\1, ...\2, ...\3)",
    )
    # Common value-shape cleanup.
    data = replace(data, r"let center_world\s*=\s*center_pixels\s*/\s*pixels_per_world_unit\(this\)" => "let center_world = {x: center_pixels.x / pixels_per_world_unit(this), y: center_pixels.y / pixels_per_world_unit(this)}")
    data = replace(data, r"(?m)^(\s*)targetPos\s*=\s*" => s"\1let targetPos = ")
    data = replace(data, r"(?m)^(\s*)targetScale\s*=\s*" => s"\1let targetScale = ")
    data = replace(data, r"\bsetfield\(([^,]+),\s*([^,]+),\s*([^)]+)\)" => s"(\1 as any)[\2 as any] = \3")
    # `@warn` / `@error` — strip trailing Julia kwargs (`exception=...`) on the same line.
    data = replace(data, r"@error\s*\(" => "console.error(")
    data = replace(data, r"(?m)@warn\s+\"([^\"]*)\".*$" => s"console.warn(\"\1\")")
    data = replace(data, r"(?m)@error\s+\"([^\"]*)\".*$" => s"console.error(\"\1\")")
    # `@error String(e)` and other expression forms (not already `console.error(`).
    data = replace(data, r"(?m)@error\s+(.+)$" => s"console.error(\1)")
    # debug with string literal
    data = replace(data, r"@debug\s+\"([^\"]*)\"" => s"console.debug(\"\1\")")
    # macro invocation style: `@debug("...")`.
    data = replace(data, r"@debug\(" => "console.debug(")
    data = replace(data, r"\bprintln\(" => "console.log(")
    # info with string literal
    data = replace(data, r"(?m)@info\s+\"([^\"]*)\".*$" => s"console.info(\"\1\")")
    data = rewrite_console_double_quoted_dollar_strings_to_templates(data)
    data = replace_julia_symbol_literals_to_ts_strings(data)
    data = replace_julia_stdlib_string_ops(data)
    data = insert_semicolon_before_line_starting_with_open_paren(data)
    data = replace_julia_string_calls_to_ts(data)
    data = replace_julia_substring_three_arg_calls(data)
    data = replace_ts_vector_object_literal_equality(data)
    data = replace_julia_dict_empty_ctor_as_object(data)
    return data
end

# Julia symbol literal values `:name` -> TS string literal `"name"`.
# Conservative rewrite: only in value-like positions, skipping quoted/template strings.
function replace_julia_symbol_literals_to_ts_strings(data::AbstractString)::String
    s = String(data)
    io = IOBuffer()
    i = firstindex(s)
    n = lastindex(s)
    is_ident_start(c::Char) = (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || c == '_'
    is_ident_char(c::Char) = is_ident_start(c) || (c >= '0' && c <= '9')
    while i <= n
        c = s[i]
        if c == '"' || c == '\'' || c == '`'
            q = c
            j = i
            write(io, q)
            j = nextind(s, j)
            while j <= n
                cj = s[j]
                write(io, cj)
                if cj == '\\'
                    j = nextind(s, j)
                    j <= n && write(io, s[j])
                    j = nextind(s, j)
                    continue
                end
                if cj == q
                    j = nextind(s, j)
                    break
                end
                j = nextind(s, j)
            end
            i = j
            continue
        end
        # `//` / `/* */` comments often contain apostrophes (`doesn't`). Treating `'` as a string opener
        # would leave the scanner "inside" a fake string and skip `:symbol` rewrites for the rest of the file.
        if c == '/' && i < n
            ni = nextind(s, i)
            if s[ni] == '/'
                while i <= n
                    ch = s[i]
                    write(io, ch)
                    if ch == '\n'
                        i = nextind(s, i)
                        break
                    elseif ch == '\r'
                        i2 = nextind(s, i)
                        if i2 <= n && s[i2] == '\n'
                            write(io, s[i2])
                            i = nextind(s, i2)
                        else
                            i = i2
                        end
                        break
                    end
                    i = nextind(s, i)
                end
                continue
            elseif s[ni] == '*'
                write(io, '/', '*')
                i = nextind(s, ni)
                while i <= n
                    ch = s[i]
                    write(io, ch)
                    if ch == '*'
                        i2 = nextind(s, i)
                        if i2 <= n && s[i2] == '/'
                            write(io, '/')
                            i = nextind(s, i2)
                            break
                        end
                    end
                    i = nextind(s, i)
                end
                continue
            end
        end
        if c == ':'
            prev_ok = false
            if i == firstindex(s)
                prev_ok = true
            else
                p = s[prevind(s, i)]
                prev_ok = isspace(p) || p in ('(', '[', '{', ',', '=', ';', '?', '+', '-', '*', '/', '%', '!', '&', '|', '^', '~', '<', '>')
            end
            if prev_ok && (i == firstindex(s) || s[prevind(s, i)] != ':')
                j = nextind(s, i)
                if j <= n && is_ident_start(s[j])
                    k = j
                    while k <= n && is_ident_char(s[k])
                        k = nextind(s, k)
                    end
                    sym = s[j:prevind(s, k)]
                    write(io, '"', sym, '"')
                    i = k
                    continue
                end
            end
        end
        write(io, c)
        i = nextind(s, i)
    end
    return String(take!(io))
end

# Julia `replace` / `split` / `join` on strings and arrays → TS `String` / `Array` builtins (no helpers).

"""Julia `replace(s, '\\\\' => '/')` — parse args with comma-splitter (regex `[^,]+?` can grab wrong prefix)."""
function replace_julia_replace_backslash_with_slash_calls(data::AbstractString)::String
    s = String(data)
    fi = firstindex(s)
    pair_pat = r"^'\s*\\\\\s*'\s*=>\s*'/'"
    changed = true
    while changed
        changed = false
        i = fi
        n = lastindex(s)
        while i <= n
            rg = findnext(r"\breplace\s*\(", s, i)
            rg === nothing && break
            lo = first(rg)
            if lo > firstindex(s) && s[prevind(s, lo)] == '.'
                i = nextind(s, last(rg))
                continue
            end
            inner_start = nextind(s, last(rg))
            close_idx = _find_outer_push_close(s, inner_start, n)
            close_idx === nothing && break
            inner = s[inner_start:prevind(s, close_idx)]
            parts = split_top_level_commas_general(inner)
            if length(parts) < 2
                i = nextind(s, lo)
                continue
            end
            p2 = strip(String(parts[2]))
            match(pair_pat, p2) === nothing && (i = nextind(s, lo); continue)
            recv = strip(String(parts[1]))
            replacement = string(recv, ".replace(/\\\\/g, '/')")
            pre = s[fi:prevind(s, lo)]
            post = s[nextind(s, close_idx):n]
            s = string(pre, replacement, post)
            changed = true
            break
        end
    end
    return s
end

"""Map Julia first arg of `join(first, "delim")` → TS receiver before `.join(...)` (supports `[N:end]` and malformed `parts[1:]}` from partial transpile)."""
function _julia_join_first_arg_to_ts_receiver(a1::AbstractString)::Union{Nothing,String}
    t = strip(String(a1))
    m = match(r"^([A-Za-z_][\w.]*)$", t)
    m !== nothing && return String(m[1])
    m = match(r"^([A-Za-z_][\w.]*)\s*\[\s*(\d+)\s*:\s*end\s*\]$", t)
    if m !== nothing
        name = String(m[1])
        n = parse(Int, String(m[2]))
        return n <= 1 ? name : string(name, ".slice(", n - 1, ")")
    end
    # After `length(x)` -> `x.length`, support `x[1:x.length]` (and general N).
    m = match(r"^([A-Za-z_][\w.]*)\s*\[\s*(\d+)\s*:\s*\1\.length\s*\]$", t)
    if m !== nothing
        name = String(m[1])
        n = parse(Int, String(m[2]))
        return n <= 1 ? name : string(name, ".slice(", n - 1, ", ", name, ".length)")
    end
    # Partial transpile typo: `parts[1:]}` instead of `parts[1:end]`
    m = match(r"^([A-Za-z_][\w.]*)\s*\[\s*(\d+)\s*:\s*\]\s*\}$", t)
    if m !== nothing
        name = String(m[1])
        n = parse(Int, String(m[2]))
        return n <= 1 ? name : string(name, ".slice(", n - 1, ")")
    end
    return nothing
end

"""Julia `join(arr, "delim")` / `join(arr[N:end], "delim")` → TS `arr.join("delim")` (parsed args; no brittle full-line regex)."""
function replace_julia_join_two_arg_calls(data::AbstractString)::String
    s = String(data)
    fi = firstindex(s)
    changed = true
    while changed
        changed = false
        i = fi
        n = lastindex(s)
        while i <= n
            rg = findnext(r"\bjoin\s*\(", s, i)
            rg === nothing && break
            lo = first(rg)
            inner_start = nextind(s, last(rg))
            close_idx = _find_outer_push_close(s, inner_start, n)
            close_idx === nothing && break
            inner = s[inner_start:prevind(s, close_idx)]
            args = split_top_level_commas_general(inner)
            if length(args) != 2
                i = nextind(s, lo)
                continue
            end
            a1 = strip(String(args[1]))
            a2 = strip(String(args[2]))
            recv = _julia_join_first_arg_to_ts_receiver(a1)
            recv === nothing && (i = nextind(s, lo); continue)
            replacement = string(recv, ".join(", a2, ")")
            pre = s[fi:prevind(s, lo)]
            post = s[nextind(s, close_idx):n]
            s = string(pre, replacement, post)
            changed = true
            break
        end
    end
    return s
end

"""`.split(...)[k]` from Julia (1-based `k`) → `.split(...)[k-1]` in TS (only `k >= 1`)."""
function rewrite_split_call_result_one_based_indices(data::AbstractString)::String
    s = String(data)
    pat = r"(\.split\((?:[^()]|\([^)]*\))*\))\[([1-9]\d*)\]"
    while true
        m = match(pat, s)
        m === nothing && break
        k = parse(Int, m[2]::AbstractString)
        replacement = string(m[1], "[", k - 1, "]")
        s = replace(s, m.match => replacement, count = 1)
    end
    return s
end

function replace_julia_stdlib_string_ops(data::AbstractString)::String
    s = String(data)
    # Two-arg `join` (plain, `[N:end]`, or bad `[N:]}`) — single scanner.
    s = replace_julia_join_two_arg_calls(s)
    # Fallback: exact malformed `join(parts[1:]}, "x")` if comma-split still failed.
    bad_join = r"\bjoin\(\s*([A-Za-z_][\w.]*)\s*\[\s*(\d+)\s*:\s*\]\s*\}\s*,\s*\"([^\"]*)\"\s*\)"
    while true
        m = match(bad_join, s)
        m === nothing && break
        name = String(m[1])
        n = parse(Int, String(m[2]))
        d = String(m[3])
        rep =
            n <= 1 ? string(name, ".join(\"", d, "\")") :
            string(name, ".slice(", n - 1, ").join(\"", d, "\")")
        s = replace(s, m.match => rep, count = 1)
    end
    # `replace(str, '\\' => '/')` path normalization (scanner — not fragile `[^,]+?`).
    s = replace_julia_replace_backslash_with_slash_calls(s)
    # `split(str, delim)` — common generated shapes only (extend as needed).
    s = replace(s, r"\bsplit\(\s*([^,]+?)\s*,\s*'/'\s*\)" => s"\1.split('/')")
    s = replace(s, r"\bsplit\(\s*([^,]+?)\s*,\s*\";base64,\"\s*\)" => s"\1.split(\";base64,\")")
    s = replace(s, r"\bsplit\(\s*([^,]+?)\s*,\s*\"\\.\"\s*\)" => s"\1.split(\".\")")
    # `split(str)` — Julia default is whitespace / Unicode space (approximate with `/\\s+/`).
    s = replace(s, r"\bsplit\(\s*([A-Za-z_][\w.]*)\s*\)" => s"\1.trim().split(/\\s+/)")
    s = rewrite_split_call_result_one_based_indices(s)
    return s
end

# Julia `string(a, b, ...)` — TS has no `string()` value; use `String(x)` or `[...].join("")`.
# Must use `\bstring` so we do not match the `string(` inside `unsafe_string(...)` (that would emit `unsafe_String(...)`).
function replace_julia_string_calls_to_ts(data::AbstractString)::String
    s = String(data)
    fi = firstindex(s)
    changed = true
    while changed
        changed = false
        i = fi
        n = lastindex(s)
        while i <= n
            rg = findnext(r"\bstring\s*\(", s, i)
            rg === nothing && break
            lo = first(rg)
            if lo > firstindex(s) && s[prevind(s, lo)] == '.'
                i = nextind(s, last(rg))
                continue
            end
            inner_start = nextind(s, last(rg))
            close_idx = _find_outer_push_close(s, inner_start, n)
            close_idx === nothing && break
            inner = s[inner_start:prevind(s, close_idx)]
            parts_stripped = map(p -> strip(String(p)), split_top_level_commas_general(inner))
            replacement = if isempty(parts_stripped) || (length(parts_stripped) == 1 && isempty(parts_stripped[1]))
                "\"\""
            elseif length(parts_stripped) == 1
                string("String(", parts_stripped[1], ")")
            else
                string("[", join(parts_stripped, ", "), "].join(\"\")")
            end
            pre = s[fi:prevind(s, lo)]
            post = s[nextind(s, close_idx):n]
            s = string(pre, replacement, post)
            changed = true
            break
        end
    end
    return s
end

# Julia `"a $b $(c)"` in `console.*("...")` — TS needs `` `a ${b} ${c}` `` (double-quoted `$` is not interpolation).
function julia_string_interpolation_to_ts_template_body(body::AbstractString)::String
    s = String(body)
    io = IOBuffer()
    i = firstindex(s)
    n = lastindex(s)
    is_word_char(c::Char) = (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c == '_'
    while i <= n
        c = s[i]
        if c == '$' && i < n
            ni = nextind(s, i)
            if s[ni] == '('
                inner_start = nextind(s, ni)
                d = 1
                j = inner_start
                found = false
                while j <= n
                    if s[j] == '('
                        d += 1
                    elseif s[j] == ')'
                        d -= 1
                        if d == 0
                            inner = s[inner_start:prevind(s, j)]
                            write(io, "\${", inner, "}")
                            i = nextind(s, j)
                            found = true
                            break
                        end
                    end
                    j = nextind(s, j)
                end
                if found
                    continue
                end
            elseif is_word_char(s[ni])
                j = ni
                id = IOBuffer()
                while j <= n && is_word_char(s[j])
                    write(id, s[j])
                    j = nextind(s, j)
                end
                idstr = String(take!(id))
                if j <= n && s[j] == '['
                    j2 = nextind(s, j)
                    if j2 <= n && s[j2] == ']'
                        write(io, "\${", idstr, "[0]}")
                        i = nextind(s, j2)
                        continue
                    end
                end
                write(io, "\${", idstr, "}")
                i = j
                continue
            end
        end
        write(io, c)
        i = nextind(s, i)
    end
    return String(take!(io))
end

function escape_ts_template_literal_content(t::AbstractString)::String
    x = replace(String(t), '\\' => "\\\\")
    x = replace(x, '`' => "\\`")
    return x
end

function rewrite_console_double_quoted_dollar_strings_to_templates(data::AbstractString)::String
    pat = r"^(\s*console\.(?:log|debug|warn|error|info)\(\s*)\"([^\"]*)\"(\s*\).*)$"
    lines = split(String(data), '\n'; keepempty = true)
    return join(
        map(lines) do line
            m = match(pat, String(line))
            m === nothing && return line
            body = String(m[2])
            occursin('$', body) || return line
            inner = julia_string_interpolation_to_ts_template_body(body)
            inner_esc = escape_ts_template_literal_content(inner)
            string(m[1], "`", inner_esc, "`", m[3])
        end,
        '\n',
    )
end

# Avoid ASI pitfalls: next line starting with `(` continues the previous expression unless ASI inserts `;`.
# e.g. `self.x = y\n(globalThis...)` parses as `y(globalThis...)`; `console.log(...)\n(...)` calls void.
const _TS_ASI_SKIP_SINGLE_KEYWORDS = Set([
    "if", "else", "for", "while", "switch", "catch", "with", "case", "default",
    "return", "throw", "break", "continue", "debugger", "function", "class",
])

# Julia line continuations (`expr ||\n    (next)`) must not get ASI `;` after the operator.
const _TS_ASI_EXPRESSION_CONTINUATION_SUFFIXES = (
    "||", "&&", "??", "+", "-", "*", "/", "%", ",", "|", "&", "^", "?", ":",
)

function _ts_line_continues_expression(cur::AbstractString)::Bool
    for op in _TS_ASI_EXPRESSION_CONTINUATION_SUFFIXES
        endswith(cur, op) && return true
    end
    return false
end

function insert_semicolon_before_line_starting_with_open_paren(data::AbstractString)::String
    lines = split(String(data), '\n'; keepempty = true)
    n = length(lines)
    for idx in 1:(n - 1)
        raw = lines[idx]
        cur = String(strip(raw))
        isempty(cur) && continue
        startswith(cur, "//") && continue
        endswith(cur, ';') && continue
        endswith(cur, '{') && continue
        endswith(cur, '(') && continue
        _ts_line_continues_expression(cur) && continue
        cur in _TS_ASI_SKIP_SINGLE_KEYWORDS && continue
        j = idx + 1
        while j <= n
            nx = String(strip(lines[j]))
            if isempty(nx) || startswith(nx, "//")
                j += 1
                continue
            end
            if startswith(nx, '(')
                lines[idx] = rstrip(raw) * ";"
            end
            break
        end
    end
    return join(lines, '\n')
end

# `Ref{Cint}(e)` / `Ref{UInt32}` / `Ref{UInt64}(e)` → TS one-element buffer `[e]` for SDL out-params.
function replace_ref_curly_primitive_buffers(data::AbstractString)::String
    s = String(data)
    needle = "Ref{"
    buf = IOBuffer()
    seg_start = firstindex(s)
    n = lastindex(s)
    while true
        rg = findnext(needle, s, seg_start)
        if rg === nothing
            seg_start <= n && write(buf, SubString(s, seg_start))
            break
        end
        lo = first(rg)
        lo > seg_start && write(buf, SubString(s, seg_start, prevind(s, lo)))
        inner_type_start = nextind(s, last(rg))
        bi = inner_type_start
        depth = 1
        type_end = nothing
        while bi <= n
            c = s[bi]
            if c == '{'
                depth += 1
            elseif c == '}'
                depth -= 1
                if depth == 0
                    type_end = bi
                    break
                end
            end
            bi = nextind(s, bi)
        end
        if type_end === nothing
            write(buf, SubString(s, lo:n))
            break
        end
        inner_type = strip(String(s[inner_type_start:prevind(s, type_end)]))
        bi2 = nextind(s, type_end)
        while bi2 <= n && Base.Unicode.isspace(s[bi2])
            bi2 = nextind(s, bi2)
        end
        if bi2 > n || s[bi2] != '('
            write(buf, SubString(s, lo, type_end))
            seg_start = nextind(s, type_end)
            continue
        end
        inner_paren_start = nextind(s, bi2)
        close_idx = _find_outer_push_close(s, inner_paren_start, n)
        if close_idx === nothing
            write(buf, SubString(s, lo:n))
            break
        end
        inner_arg = s[inner_paren_start:prevind(s, close_idx)]
        repl = if inner_type == "Cint" || inner_type == "UInt32" || inner_type == "UInt64"
            string("[", inner_arg, "]")
        else
            nothing
        end
        if repl !== nothing
            write(buf, repl)
            seg_start = nextind(s, close_idx)
        else
            write(buf, SubString(s, lo, close_idx))
            seg_start = nextind(s, close_idx)
        end
    end
    return String(take!(buf))
end

