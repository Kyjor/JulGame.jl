function _line_brace_delta(line::AbstractString)::Int
    d = 0
    for c in line
        if c == '{'
            d += 1
        elseif c == '}'
            d -= 1
        end
    end
    return d
end

function _read_braced_block_lines(lines::Vector{SubString{String}}, start_i::Int)::Tuple{Int, Vector{String}}
    balance = 0
    body = String[]
    i = start_i
    n = length(lines)
    while i <= n
        line = String(lines[i])
        push!(body, line)
        balance += _line_brace_delta(line)
        i += 1
        balance <= 0 && break
    end
    return (i, body)
end

"""Julia `f(scene, x)` + `f(x) = f(MAIN.scene, x)` → one TS function with `typeof` dispatch."""
function merge_main_scene_delegating_overloads(data::AbstractString)::String
    lines = split(String(data), '\n'; keepempty=true)
    out = String[]
    i = 1
    n = length(lines)
    inst_pat = r"^(\s*)function\s+(\w+)\(self:\s*(\w+),\s*(\w+)(?::\s*string)?\)\s*\{"
    while i <= n
        line = String(lines[i])
        m = match(inst_pat, line)
        if m === nothing
            push!(out, line)
            i += 1
            continue
        end
        indent, fname, typ, arg = String(m.captures[1]), String(m.captures[2]), String(m.captures[3]), String(m.captures[4])
        inst_end, inst_body = _read_braced_block_lines(lines, i)
        j = inst_end
        while j <= n && isempty(strip(String(lines[j])))
            j += 1
        end
        if j > n || length(inst_body) < 2
            append!(out, inst_body)
            i = inst_end
            continue
        end
        deleg_open = match(Regex("^\\s*function\\s+" * fname * "\\(" * arg * ":\\s*string\\)\\s*\\{"), String(lines[j]))
        if deleg_open === nothing
            append!(out, inst_body)
            i = inst_end
            continue
        end
        deleg_end, deleg_body = _read_braced_block_lines(lines, j)
        deleg_text = join(deleg_body, '\n')
        main_scene_deleg =
            occursin("return $fname(MAIN.scene, $arg)", deleg_text) ||
            occursin("return $fname((globalThis as any).MAIN.scene, $arg)", deleg_text) ||
            occursin("return $fname((globalThis as any).JulGame.MAIN.scene, $arg)", deleg_text)
        if !main_scene_deleg
            append!(out, inst_body)
            i = inst_end
            continue
        end
        inner = join(inst_body[2:(end - 1)], '\n')
        push!(
            out,
            string(
                indent,
                "function ",
                fname,
                "(selfOrName: ",
                typ,
                " | string, ",
                arg,
                "?: string) {\n",
                indent,
                "    if (typeof selfOrName === \"string\") {\n",
                indent,
                "        return ",
                fname,
                "((globalThis as any).MAIN.scene, selfOrName)\n",
                indent,
                "    }\n",
                indent,
                "    const self = selfOrName\n",
                inner,
                "\n",
                indent,
                "}",
            ),
        )
        i = deleg_end
    end
    return join(out, '\n')
end

# Strip a whole `function name(...) { ... }` (names are already TS/mangled). `r"...$var"` does not interpolate.
function remove_ts_function_block(s::String, func::AbstractString)::String
    pat = Regex("(?m)^\\s*function\\s+" * func * "\\s*\\([^)]*\\)\\s*\\{")
    while true
        rg = findfirst(pat, s)
        rg === nothing && return s
        lo = first(rg)
        hi = last(rg)  # `{` that opens the body

        depth = 1
        p = nextind(s, hi)
        n = lastindex(s)
        while p <= n && depth > 0
            c = s[p]
            if c == '{'
                depth += 1
            elseif c == '}'
                depth -= 1
            end
            p = nextind(s, p)
        end

        fi = firstindex(s)
        prefix = lo > fi ? s[fi:prevind(s, lo)] : ""
        suffix = p <= n ? s[p:n] : ""
        s = string(prefix, suffix)
    end
end

# Julia named-tuple / kwargs call shape `a=x, b=y` → TS single-arg object `{ a: x, b: y }` (shorthand when `a==x`).
function _named_julia_kwargs_to_ts_object(inner::AbstractString)::Union{Nothing,String}
    t = String(strip(inner))
    isempty(t) && return nothing
    occursin('=', t) || return nothing
    parts = split_top_level_commas_general(t)
    props = String[]
    for p in parts
        pt = String(strip(p))
        pm = match(r"^([A-Za-z_]\w*)\s*=\s*(.+)$", pt)
        pm === nothing && return nothing
        k = String(pm[1])
        v = String(strip(String(pm[2])))
        if v == k
            push!(props, k)
        else
            push!(props, string(k, ": ", v))
        end
    end
    isempty(props) && return nothing
    return string("{ ", join(props, ", "), " }")
end

# Convert calls whose entire argument list is `name=value` pairs (no positional args).
function replace_keyword_style_calls_to_object_args(data::AbstractString)::String
    s = String(data)
    out = IOBuffer()
    i = firstindex(s)
    n = lastindex(s)
    pat_call = r"\b([A-Za-z_]\w*)\("
    while i <= n
        rg = findnext(pat_call, s, i)
        if rg === nothing
            write(out, SubString(s, i:n))
            break
        end
        lo = first(rg)
        lo > i && write(out, SubString(s, i, prevind(s, lo)))
        m = match(pat_call, s, lo)
        m === nothing && (write(out, s[lo]); i = nextind(s, lo); continue)
        fname = String(m.captures[1])
        open_paren = last(rg)
        inner_start = nextind(s, open_paren)
        close_idx = _find_outer_push_close(s, inner_start, n)
        if close_idx === nothing
            write(out, SubString(s, lo:lo))
            i = nextind(s, lo)
            continue
        end
        inner = s[inner_start:prevind(s, close_idx)]
        obj = _named_julia_kwargs_to_ts_object(inner)
        if obj !== nothing
            write(out, fname, "(", obj, ")")
            i = nextind(s, close_idx)
        else
            write(out, SubString(s, lo:close_idx))
            i = nextind(s, close_idx)
        end
    end
    return String(take!(out))
end

# `Base.invokelatest(f)` → `f()`; `Base.invokelatest(f, a, b)` → `f(a, b)`;
# `Base.invokelatest(f, (a=x, b=y))` → `f({ a: x, b: y })` (TS options object, not fake keyword args).
function replace_invokelatest_calls(data::AbstractString)::String
    s = String(data)
    needle = "Base.invokelatest("
    buf = IOBuffer()
    seg_start = firstindex(s)
    n = lastindex(s)
    while true
        rg = findnext(needle, s, seg_start)
        if rg === nothing
            seg_start <= n && write(buf, SubString(s, seg_start))
            break
        end
        lo = first(rg)
        lo > seg_start && write(buf, SubString(s, seg_start, prevind(s, lo)))
        inner_start = nextind(s, last(rg))
        close_idx = _find_outer_push_close(s, inner_start, n)
        if close_idx === nothing
            write(buf, SubString(s, lo:n))
            break
        end
        inner = s[inner_start:prevind(s, close_idx)]
        parts = split_top_level_commas_general(inner)
        callee = isempty(parts) ? "" : strip(parts[1])
        if isempty(callee)
            write(buf, SubString(s, lo:close_idx))
            seg_start = nextind(s, close_idx)
            continue
        end
        replacement =
            if length(parts) == 1
                string(callee, "()")
            else
                rest = map(strip, parts[2:end])
                arg_inner =
                    if length(rest) == 1
                        u = _strip_one_outer_paren_pair(rest[1])
                        core = u === nothing ? rest[1] : u
                        obj = _named_julia_kwargs_to_ts_object(core)
                        obj === nothing ? core : obj
                    else
                        mapped = map(rest) do seg
                            seg = String(strip(seg))
                            u = _strip_one_outer_paren_pair(seg)
                            core = u === nothing ? seg : u
                            obj = _named_julia_kwargs_to_ts_object(core)
                            obj === nothing ? seg : obj
                        end
                        join(mapped, ", ")
                    end
                string(callee, "(", arg_inner, ")")
            end
        write(buf, replacement)
        seg_start = nextind(s, close_idx)
    end
    return String(take!(buf))
end

# `push!(collection, item)` → `collection.push(item)` (balanced parens/brackets; skips `"..."` segments).
function replace_push_calls(data::AbstractString)::String
    s = String(data)
    needle = "push!("
    buf = IOBuffer()
    seg_start = firstindex(s)
    n = lastindex(s)
    while true
        rg = findnext(needle, s, seg_start)
        if rg === nothing
            seg_start <= n && write(buf, SubString(s, seg_start))
            break
        end
        lo = first(rg)
        lo > seg_start && write(buf, SubString(s, seg_start, prevind(s, lo)))
        inner_start = nextind(s, last(rg))
        res = _parse_push_two_args(s, inner_start, n)
        if res === nothing
            close_idx = _find_outer_push_close(s, inner_start, n)
            if close_idx === nothing
                write(buf, SubString(s, lo:n))
                break
            end
            write(buf, SubString(s, lo:close_idx))
            seg_start = nextind(s, close_idx)
            continue
        end
        arg1, arg2, close_idx = res
        write(buf, strip(String(arg1)), ".push(", strip(String(arg2)), ")")
        seg_start = nextind(s, close_idx)
    end
    return String(take!(buf))
end

# `popfirst!(collection)` / `popfirst(collection)` (after `!(` → `(`) → `collection.shift()`.
function replace_popfirst_calls(data::AbstractString)::String
