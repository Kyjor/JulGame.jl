function replace_if_statements(data::AbstractString)
    # Julia: `if cond` / `if(cond)` — TS: `if (cond) {`. Trailing line comment preserved after `{`.
    s = String(data)
    lines = split(s, '\n'; keepempty = true)
    done_line = r"^\s*if\s*\([^)]*\)\s*\{\s*$"
    pat = r"^(\s*)if\b\s*(.+)$"
    return join(
        map(lines) do line
            occursin(done_line, line) && return line
            m = match(pat, line)
            if m === nothing
                line
            else
                raw = String(m[2])
                cond, cmt = _split_trailing_ts_comment(raw)
                cond = String(strip(cond))
                if startswith(cond, "(") && endswith(cond, ")")
                    cond = String(strip(chop(cond, head = 1, tail = 1)))
                end
                string(m[1], "if (", cond, ") {", cmt)
            end
        end,
        '\n',
    )
end

function replace_first_assignments_with_let(data::AbstractString)::String
    lines = split(String(data), '\n'; keepempty = true)
    seen = Set{String}()
    pat = r"^(\s*)([A-Za-z_]\w*)\s*=\s*(.+)$"
    header_pat = r"^\s*(?:function\s+[^\s(]+|constructor)\s*\(([^)]*)\)"
    out = map(lines) do line
        hm = match(header_pat, line)
        if hm !== nothing
            # Fresh scope per function/constructor — Julia can reuse names (`error`) across functions.
            empty!(seen)
            params = split(String(hm[1]), ',')
            for p in params
                pm = match(r"^\s*([A-Za-z_]\w*)", p)
                pm === nothing && continue
                push!(seen, String(pm[1]))
            end
            return line
        end
        m = match(pat, line)
        m === nothing && return line
        indent = String(m[1])
        name = String(m[2])
        rhs = String(m[3])
        # Skip obvious non-declarations / already-TS declarations.
        startswith(rhs, "=") && return line  # `==`, `===`
        startswith(rhs, ">") && return line  # `=>`
        startswith(rhs, "<") && return line  # `=<` / malformed cases
        startswith(name, "this") && return line
        if name in seen
            return line
        end
        push!(seen, name)
        return string(indent, "let ", name, " = ", rhs)
    end
    return join(out, '\n')
end

