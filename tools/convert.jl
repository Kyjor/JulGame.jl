# Strip a whole `function name(...) { ... }` (names are already TS/mangled). `r"...$var"` does not interpolate.
function remove_ts_function_block(s::String, func::AbstractString)::String
    pat = Regex("(?m)^\\s*function\\s+" * func * "\\s*\\([^)]*\\)\\s*\\{")
    while true
        rg = findfirst(pat, s)
        rg === nothing && return s
        lo = first(rg)
        hi = last(rg)  # `{` that opens the body

        depth = 1
        p = nextind(s, hi)
        n = lastindex(s)
        while p <= n && depth > 0
            c = s[p]
            if c == '{'
                depth += 1
            elseif c == '}'
                depth -= 1
            end
            p = nextind(s, p)
        end

        fi = firstindex(s)
        prefix = lo > fi ? s[fi:prevind(s, lo)] : ""
        suffix = p <= n ? s[p:n] : ""
        s = string(prefix, suffix)
    end
end

# Julia named-tuple / kwargs call shape `a=x, b=y` → TS single-arg object `{ a: x, b: y }` (shorthand when `a==x`).
function _named_julia_kwargs_to_ts_object(inner::AbstractString)::Union{Nothing,String}
    t = String(strip(inner))
    isempty(t) && return nothing
    occursin('=', t) || return nothing
    parts = split_top_level_commas_general(t)
    props = String[]
    for p in parts
        pt = String(strip(p))
        pm = match(r"^([A-Za-z_]\w*)\s*=\s*(.+)$", pt)
        pm === nothing && return nothing
        k = String(pm[1])
        v = String(strip(String(pm[2])))
        if v == k
            push!(props, k)
        else
            push!(props, string(k, ": ", v))
        end
    end
    isempty(props) && return nothing
    return string("{ ", join(props, ", "), " }")
end

# Convert calls whose entire argument list is `name=value` pairs (no positional args).
function replace_keyword_style_calls_to_object_args(data::AbstractString)::String
    s = String(data)
    out = IOBuffer()
    i = firstindex(s)
    n = lastindex(s)
    pat_call = r"\b([A-Za-z_]\w*)\("
    while i <= n
        rg = findnext(pat_call, s, i)
        if rg === nothing
            write(out, SubString(s, i:n))
            break
        end
        lo = first(rg)
        lo > i && write(out, SubString(s, i, prevind(s, lo)))
        m = match(pat_call, s, lo)
        m === nothing && (write(out, s[lo]); i = nextind(s, lo); continue)
        fname = String(m.captures[1])
        open_paren = last(rg)
        close_idx = _find_outer_push_close(s, open_paren, n)
        if close_idx === nothing
            write(out, SubString(s, lo:lo))
            i = nextind(s, lo)
            continue
        end
        inner = s[nextind(s, open_paren):prevind(s, close_idx)]
        obj = _named_julia_kwargs_to_ts_object(inner)
        if obj !== nothing
            write(out, fname, "(", obj, ")")
            i = nextind(s, close_idx)
        else
            write(out, SubString(s, lo:close_idx))
            i = nextind(s, close_idx)
        end
    end
    return String(take!(out))
end

# `Base.invokelatest(f)` → `f()`; `Base.invokelatest(f, a, b)` → `f(a, b)`;
# `Base.invokelatest(f, (a=x, b=y))` → `f({ a: x, b: y })` (TS options object, not fake keyword args).
function replace_invokelatest_calls(data::AbstractString)::String
    s = String(data)
    needle = "Base.invokelatest("
    buf = IOBuffer()
    seg_start = firstindex(s)
    n = lastindex(s)
    while true
        rg = findnext(needle, s, seg_start)
        if rg === nothing
            seg_start <= n && write(buf, SubString(s, seg_start))
            break
        end
        lo = first(rg)
        lo > seg_start && write(buf, SubString(s, seg_start, prevind(s, lo)))
        inner_start = nextind(s, last(rg))
        close_idx = _find_outer_push_close(s, inner_start, n)
        if close_idx === nothing
            write(buf, SubString(s, lo:n))
            break
        end
        inner = s[inner_start:prevind(s, close_idx)]
        parts = split_top_level_commas_general(inner)
        callee = isempty(parts) ? "" : strip(parts[1])
        if isempty(callee)
            write(buf, SubString(s, lo:close_idx))
            seg_start = nextind(s, close_idx)
            continue
        end
        replacement =
            if length(parts) == 1
                string(callee, "()")
            else
                rest = map(strip, parts[2:end])
                arg_inner =
                    if length(rest) == 1
                        u = _strip_one_outer_paren_pair(rest[1])
                        core = u === nothing ? rest[1] : u
                        obj = _named_julia_kwargs_to_ts_object(core)
                        obj === nothing ? core : obj
                    else
                        mapped = map(rest) do seg
                            seg = String(strip(seg))
                            u = _strip_one_outer_paren_pair(seg)
                            core = u === nothing ? seg : u
                            obj = _named_julia_kwargs_to_ts_object(core)
                            obj === nothing ? seg : obj
                        end
                        join(mapped, ", ")
                    end
                string(callee, "(", arg_inner, ")")
            end
        write(buf, replacement)
        seg_start = nextind(s, close_idx)
    end
    return String(take!(buf))
end

# `push!(collection, item)` → `collection.push(item)` (balanced parens/brackets; skips `"..."` segments).
function replace_push_calls(data::AbstractString)::String
    s = String(data)
    needle = "push!("
    buf = IOBuffer()
    seg_start = firstindex(s)
    n = lastindex(s)
    while true
        rg = findnext(needle, s, seg_start)
        if rg === nothing
            seg_start <= n && write(buf, SubString(s, seg_start))
            break
        end
        lo = first(rg)
        lo > seg_start && write(buf, SubString(s, seg_start, prevind(s, lo)))
        inner_start = nextind(s, last(rg))
        res = _parse_push_two_args(s, inner_start, n)
        if res === nothing
            close_idx = _find_outer_push_close(s, inner_start, n)
            if close_idx === nothing
                write(buf, SubString(s, lo:n))
                break
            end
            write(buf, SubString(s, lo:close_idx))
            seg_start = nextind(s, close_idx)
            continue
        end
        arg1, arg2, close_idx = res
        write(buf, strip(String(arg1)), ".push(", strip(String(arg2)), ")")
        seg_start = nextind(s, close_idx)
    end
    return String(take!(buf))
end

function _find_outer_push_close(s::String, inner_start::Int, n::Int)::Union{Nothing, Int}
    i = inner_start
    paren = 1
    bracket = 0
    brace = 0
    while i <= n
        c = s[i]
        if c == '"'
            i = _skip_double_quoted_string(s, i, n)
            i > n && return nothing
            i = nextind(s, i)
            continue
        end
        if c == '('
            paren += 1
        elseif c == ')'
            paren -= 1
            if paren == 0
                return i
            end
        elseif c == '['
            bracket += 1
        elseif c == ']'
            bracket -= 1
        elseif c == '{'
            brace += 1
        elseif c == '}'
            brace -= 1
        end
        i = nextind(s, i)
    end
    return nothing
end

function _skip_double_quoted_string(s::String, open_quote_at::Int, n::Int)::Int
    i = nextind(s, open_quote_at)
    while i <= n
        c = s[i]
        if c == '\\'
            i = nextind(s, i)
            i = nextind(s, i)
            continue
        end
        if c == '"'
            return i
        end
        i = nextind(s, i)
    end
    return i
end

function _parse_push_two_args(s::String, inner_start::Int, n::Int)::Union{Nothing, Tuple{SubString{String}, SubString{String}, Int}}
    i = inner_start
    paren = 1
    bracket = 0
    brace = 0
    arg1_lo = i
    split_at = nothing
    while i <= n
        c = s[i]
        if c == '"'
            i = _skip_double_quoted_string(s, i, n)
            i > n && return nothing
            i = nextind(s, i)
            continue
        end
        if c == '('
            paren += 1
        elseif c == ')'
            paren -= 1
            if paren == 0
                return nothing
            end
        elseif c == '['
            bracket += 1
        elseif c == ']'
            bracket -= 1
        elseif c == '{'
            brace += 1
        elseif c == '}'
            brace -= 1
        elseif c == ',' && paren == 1 && bracket == 0 && brace == 0
            split_at = i
            break
        end
        i = nextind(s, i)
    end
    split_at === nothing && return nothing
    arg1 = SubString(s, arg1_lo, prevind(s, split_at))
    i = nextind(s, split_at)
    arg2_lo = i
    while i <= n
        c = s[i]
        if c == '"'
            i = _skip_double_quoted_string(s, i, n)
            i > n && return nothing
            i = nextind(s, i)
            continue
        end
        if c == '('
            paren += 1
        elseif c == ')'
            paren -= 1
            if paren == 0
                arg2 = SubString(s, arg2_lo, prevind(s, i))
                return (arg1, arg2, i)
            end
        elseif c == '['
            bracket += 1
        elseif c == ']'
            bracket -= 1
        elseif c == '{'
            brace += 1
        elseif c == '}'
            brace -= 1
        end
        i = nextind(s, i)
    end
    return nothing
end

function remove_!_from_function_names(data::AbstractString)
    return replace(data, "!(" => "(")
end

function source_files_from_manifest(; repo_root::AbstractString = REPO_ROOT)::Vector{String}
    manifest = joinpath(repo_root, "ts", "files-needed.txt")
    isfile(manifest) || return String[]
    wanted = String[]
    for raw in split(read(manifest, String), '\n')
        name = strip(raw)
        isempty(name) && continue
        push!(wanted, endswith(name, ".jl") ? name : name * ".jl")
    end

    # Build basename -> absolute file map once from src/.
    by_name = Dict{String, Vector{String}}()
    src_root = joinpath(repo_root, "src")
    for (dir, _, files) in walkdir(src_root)
        for f in files
            !endswith(f, ".jl") && continue
            abs = joinpath(dir, f)
            if haskey(by_name, f)
                push!(by_name[f], abs)
            else
                by_name[f] = [abs]
            end
        end
    end

    selected = String[]
    for name in wanted
        matches = get(by_name, name, String[])
        isempty(matches) && error("files-needed entry not found in src/: $name")
        length(matches) > 1 && error("files-needed entry is ambiguous in src/: $name")
        push!(selected, first(matches))
    end
    return selected
end

# If any line of a TS `if (...) { ... }` block contains `needle`, replace the **whole** block with `value`
# (`value == ""` deletes it). Keys are plain substrings — no regex. First matching key (dict order) wins.
# Example: `TS_IF_BLOCKS_REMOVE_OR_REPLACE_WHEN_CONTAINS["haskey((globalThis as any).JulGame.AUDIO_CACHE"] = ""`
const TS_IF_BLOCKS_REMOVE_OR_REPLACE_WHEN_CONTAINS = Dict{String,String}(
    "haskey((globalThis as any).JulGame.AUDIO_CACHE" => "",
    "haskey((globalThis as any).JulGame.IMAGE_CACHE" => "",
    "usingEffectTex" => "",
)

function _find_ts_if_opening_brace_on_line(ln::AbstractString, cond_paren_inner_start::Int)::Union{Nothing, Int}
    s = String(ln)
    close_cond = _find_outer_push_close(s, cond_paren_inner_start, lastindex(s))
    close_cond === nothing && return nothing
    j = nextind(s, close_cond)
    n = lastindex(s)
    while j <= n
        c = s[j]
        if c == '"'
            j = _skip_double_quoted_string(s, j, n)
            j = nextind(s, j)
            continue
        end
        c == '{' && return j
        j = nextind(s, j)
    end
    return nothing
end

# Returns (start_line_idx, end_line_idx) 1-based inclusive for the `if` line through its matching closing `}`.
function _find_ts_if_block_line_range(lines::Vector{String}, start_line::Int)::Union{Nothing, Tuple{Int, Int}}
    start_line <= length(lines) || return nothing
    ln = lines[start_line]
    occursin(r"^\s*if\s*\(", ln) || return nothing
    m = match(r"^\s*if\s*\(\s*", ln)
    m === nothing && return nothing
    cond_inner = nextind(ln, lastindex(String(m.match)))
    brace_at = _find_ts_if_opening_brace_on_line(ln, cond_inner)
    brace_at === nothing && return nothing
    depth = 1
    li = start_line
    i = nextind(ln, brace_at)
    nlines = length(lines)
    while li <= nlines
        cur = lines[li]
        n = lastindex(cur)
        while i <= n
            c = cur[i]
            if c == '"'
                i = _skip_double_quoted_string(cur, i, n)
                i > n && return nothing
                i = nextind(cur, i)
                continue
            end
            if c == '{'
                depth += 1
            elseif c == '}'
                depth -= 1
                if depth == 0
                    return (start_line, li)
                end
            end
            i = nextind(cur, i)
        end
        li += 1
        li > nlines && break
        i = firstindex(lines[li])
    end
    return nothing
end

function replace_ts_if_blocks_when_block_contains_substring(data::AbstractString)::String
    isempty(TS_IF_BLOCKS_REMOVE_OR_REPLACE_WHEN_CONTAINS) && return String(data)
    lines = split(String(data), '\n'; keepempty = true)
    ls = collect(String.(lines))
    changed = true
    while changed
        changed = false
        for i in 1:length(ls)
            occursin(r"^\s*if\s*\(", ls[i]) || continue
            rg = _find_ts_if_block_line_range(ls, i)
            rg === nothing && continue
            lo, hi = rg
            block_text = join(view(ls, lo:hi), '\n')
            hit = false
            replacement = ""
            for (needle, repl) in TS_IF_BLOCKS_REMOVE_OR_REPLACE_WHEN_CONTAINS
                if occursin(needle, block_text)
                    replacement = repl
                    hit = true
                    break
                end
            end
            if !hit
                continue
            end
            rep_lines = if isempty(replacement)
                String[]
            else
                collect(String.(split(String(replacement), '\n'; keepempty = true)))
            end
            splice!(ls, lo:hi, rep_lines)
            changed = true
            break
        end
    end
    return join(ls, '\n')
end

function replace_entire_line_if_matches(data::AbstractString)::String
    # Ordered rules: first match wins. If `needle` appears anywhere on a line, the whole line becomes `replacement`.
    # Build with `push!` so eltype stays `Pair{Union{String,Regex},String}` (avoid literal-array inference bugs).
    line_rules = Pair{Union{String, Regex}, String}[]
    push!(line_rules, "add_observer" => "")
    push!(line_rules, "throw(" => "")
    push!(line_rules, "update_effects(" => "")
    push!(line_rules, "texture_to_render = self.effectTexture" => "")
    push!(line_rules, "show_backtrace" => "")
    push!(line_rules, "@error" => "")
    lines = split(String(data), '\n'; keepempty = true)
    out = map(lines) do line
        for (needle, replacement) in line_rules
            occursin(needle, line) && return String(replacement)
        end
        line
    end
    return join(out, '\n')
end

function main()
    files = String[]
    if !isempty(ARGS)
        for a in ARGS
            p = isabspath(a) ? String(a) : joinpath(REPO_ROOT, String(a))
            isfile(p) || error("not a file: $p")
            push!(files, p)
        end
    else
        append!(files, source_files_from_manifest())
    end
    isempty(files) && (files = [joinpath(REPO_ROOT, "src", "MainLoop.jl")])
    # Smallest-first helps us iterate patterns safely from simpler files upward.
    sort!(files, by = f -> filesize(f))
    mkpath(default_out_dir())
    for f in files
        isfile(f) || error("not a file: $f")
        println(transpile_file(f))
    end
end

main()
